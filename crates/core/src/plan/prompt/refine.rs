/// Host-environment impossibility declared by an Architect synthesis round.
///
/// The payload is the very `abort` shape the structured edit contour publishes,
/// so the three fields name the same thing in both contours: the flag states
/// whether the report is active, `reason` names the concrete missing capability,
/// and `recommendation` carries the exact command the developer must run.
///
/// The flag is spelled `is_aborted` because that is the wire name the shared
/// schema declares; the protocol-layer `StructuredAbortProposal` keeps its own
/// edit-contour spelling untouched.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct PlanRefinementAbort {
    #[serde(default)]
    pub is_aborted: bool,
    #[serde(default)]
    pub reason: String,
    #[serde(default)]
    pub recommendation: String,
}

/// Output of deep plan refinement generated by the architect model.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct PlanRefinementOutput {
    pub status: String,
    pub explanation: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub reason: Option<String>,
    /// Host-environment impossibility that only the developer can repair.
    ///
    /// An absent field decodes as no abort, so every payload written before the
    /// escape hatch existed keeps decoding unchanged.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub abort: Option<PlanRefinementAbort>,
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub context_requests: Vec<String>,
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub repo_searches: Vec<RepoSearchRequest>,
    #[serde(
        default,
        deserialize_with = "deserialize_repo_map_paths",
        skip_serializing_if = "Vec::is_empty"
    )]
    pub repo_maps: Vec<String>,
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub items: Vec<PlanItem>,
}

/// Deserializes the `repo_maps` field of [`PlanRefinementOutput`].
///
/// A `null` payload yields an empty list, and every entry is normalized through
/// [`normalize_repo_map_path`], so a decoded architect output can never carry a
/// contour request that addresses a location outside the repository.
fn deserialize_repo_map_paths<'de, D>(deserializer: D) -> Result<Vec<String>, D::Error>
where
    D: serde::Deserializer<'de>,
{
    let paths = Option::<Vec<String>>::deserialize(deserializer)?;
    Ok(paths
        .unwrap_or_default()
        .iter()
        .filter_map(|path| normalize_repo_map_path(path))
        .collect())
}

/// Parses the raw JSON string returned by the model into a `PlanRefinementOutput`.
///
/// Decoding goes through the shared structured-output helpers
/// (`strip_code_fence`, `first_json_object_str`) so this parser behaves exactly
/// like every other structured-output parser in the engine: a markdown code
/// fence is unwrapped first, and when the payload is surrounded by wrapper
/// prose the outermost balanced JSON object is extracted instead of failing on
/// trailing or leading characters.
pub fn parse_plan_refinement_output(raw_json: &str) -> anyhow::Result<PlanRefinementOutput> {
    let unfenced = strip_code_fence(raw_json);
    let error = match serde_json::from_str::<PlanRefinementOutput>(unfenced) {
        Ok(output) => return Ok(output),
        Err(error) => error,
    };
    if let Some(object) = first_json_object_str(raw_json) {
        if let Ok(output) = serde_json::from_str::<PlanRefinementOutput>(object) {
            return Ok(output);
        }
    }
    Err(anyhow::anyhow!(
        "Failed to parse plan refinement JSON output: {error}"
    ))
}

/// Maximum supported hierarchy nesting depth for structured plan refinement output.
pub const MAX_PLAN_REFINEMENT_DEPTH: usize = 5;

/// Target size range (in changed lines) for one cohesive leaf implementation step.
const LEAF_STEP_TARGET_LINES: (usize, usize) = (150, 400);

/// Helper that builds an unrolled, non-recursive PlanItem JSON Schema up to `max_depth`.
fn plan_item_schema(depth: usize, max_depth: usize) -> serde_json::Value {
    let mut properties = serde_json::Map::new();
    properties.insert(
        "id".to_string(),
        serde_json::json!({
            "type": "string",
            "description": "Step identifier (e.g. '1', '1.1', '2')"
        }),
    );
    properties.insert(
        "title".to_string(),
        serde_json::json!({
            "type": "string",
            "description": "Concise step title formulated strictly in the same natural language as the plan description"
        }),
    );
    properties.insert(
        "details".to_string(),
        serde_json::json!({
            "anyOf": [
                { "type": "string" },
                { "type": "null" }
            ],
            "description": "Concrete technical details in the same language as the plan description: target files, functions, contracts, verification criteria"
        }),
    );
    properties.insert(
        "status".to_string(),
        serde_json::json!({
            "type": "string",
            "enum": ["discussion", "todo", "in_progress", "done", "cancelled"],
            "description": "Step status"
        }),
    );
    properties.insert(
        "files".to_string(),
        serde_json::json!({
            "type": "array",
            "description": "Repository-relative file paths that this step creates, modifies, or inspects (pre-loaded into context when executing). Invariant: files must only be specified for executable leaf steps without children; parent container items must have an empty files list.",
            "items": { "type": "string" }
        }),
    );
    properties.insert(
        "readonly_files".to_string(),
        serde_json::json!({
            "type": "array",
            "description": "Repository-relative file paths for read-only reference context (subsystem conventions like Conventions.md, interface contracts, protocol types). Invariant: readonly_files must only be specified for executable leaf steps without children; parent container items must have an empty readonly_files list.",
            "items": { "type": "string" }
        }),
    );
    properties.insert(
        "outer_docs".to_string(),
        serde_json::json!({
            "type": "array",
            "description": "Identifiers of the project-declared `[[outer_docs]]` entries materialized as read-only reference context when this step executes: `id` names a declared root document and `id/relative.md` names a document below that root. Invariant: outer_docs must only be specified for executable leaf steps without children; parent container items must have an empty outer_docs list.",
            "items": { "type": "string" }
        }),
    );
    properties.insert(
        "concept_refs".to_string(),
        serde_json::json!({
            "type": "array",
            "description": "IDs of concept items from the architectural concept tree that this step addresses or implements",
            "items": { "type": "string" }
        }),
    );
    properties.insert(
        "depends_on".to_string(),
        serde_json::json!({
            "type": "array",
            "description": "IDs of prerequisite steps that must reach DONE status before this step can execute (DAG edges). Only reference earlier steps. Must be empty for steps without prerequisites. Invariant: depends_on must only be specified for executable leaf steps without children; parent container items must have an empty depends_on list.",
            "items": { "type": "string" }
        }),
    );
    properties.insert(
        "commit".to_string(),
        serde_json::json!({
            "anyOf": [
                { "type": "string" },
                { "type": "null" }
            ],
            "description": "Identifier of the Git commit that already completed this step, or null for a step that has not run yet. The harness records a commit for a finished step and reproduces it verbatim, so a horizon never invents one."
        }),
    );

    let mut required = vec![
        serde_json::Value::String("id".to_string()),
        serde_json::Value::String("title".to_string()),
        serde_json::Value::String("details".to_string()),
        serde_json::Value::String("status".to_string()),
        serde_json::Value::String("commit".to_string()),
        serde_json::Value::String("files".to_string()),
        serde_json::Value::String("readonly_files".to_string()),
        serde_json::Value::String("outer_docs".to_string()),
        serde_json::Value::String("concept_refs".to_string()),
        serde_json::Value::String("depends_on".to_string()),
    ];

    if depth < max_depth {
        properties.insert(
            "children".to_string(),
            serde_json::json!({
                "type": "array",
                "description": "Sub-steps or child items",
                "items": plan_item_schema(depth + 1, max_depth)
            }),
        );
        required.push(serde_json::Value::String("children".to_string()));
    }

    serde_json::json!({
        "type": "object",
        "description": if depth < max_depth {
            "A refined step or item in the plan"
        } else {
            "A leaf step at maximum hierarchy depth (cannot have children)"
        },
        "properties": properties,
        "required": required,
        "additionalProperties": false
    })
}

/// Returns the `abort` property of the horizon-synthesis response contract.
///
/// A host-environment impossibility is reported through the very field the edit
/// contour publishes, so the three-field wire shape (`is_aborted`, `reason`,
/// `recommendation`, all required and closed to unknown keys) is declared once
/// in `crate::capabilities::schema` and only forwarded here. The plan contour
/// therefore holds no escape hatch of its own, and a change to the shape reaches
/// both contours at once.
fn abort_property() -> serde_json::Value {
    crate::capabilities::abort_fragment()["abort"].clone()
}

/// Strict JSON Schema for deep plan refinement output.
///
/// Unrolls nested plan items up to `MAX_PLAN_REFINEMENT_DEPTH` to guarantee
/// compliance with LLM Structured Output engines that forbid recursive `$ref` schemas.
pub fn plan_refine_response_schema() -> serde_json::Value {
    let items_description = format!(
        "New unfinished horizon: the hierarchical list of NEW executable steps (up to {} levels of nesting). Do NOT include already-DONE steps; the harness preserves and prepends the completed foundation. If status is 'blocked' or 'needs_context', or when an active `abort` supersedes the synthesis, this must be empty.",
        MAX_PLAN_REFINEMENT_DEPTH
    );
    let abort = abort_property();
    serde_json::json!({
        "type": "object",
        "properties": {
            "status": {
                "type": "string",
                "enum": ["success", "blocked", "needs_context"],
                "description": "Result status: 'success' if the unfinished horizon was synthesized into actionable steps, 'blocked' if architectural blockers exist, or 'needs_context' if specific source files from repo_map must be inspected before designing the roadmap."
            },
            "explanation": {
                "type": "string",
                "description": "Concise summary of the decomposition strategy and its key trade-offs, strictly in the same language as the plan description. Final distilled content only: no chain-of-thought, deliberation, or intermediate reasoning steps."
            },
            "reason": {
                "anyOf": [
                    { "type": "string" },
                    { "type": "null" }
                ],
                "description": "Required when status is 'blocked': detailed technical explanation in the same language as the plan description of the contradiction, missing prerequisite, or codebase blocker."
            },
            "abort": abort,
            "context_requests": {
                "type": "array",
                "description": "Used when status is 'needs_context': repository-relative file paths from <repo_map> or previous search results that need to be read to verify contracts and inspect implementation details.",
                "items": {
                    "type": "string",
                    "description": "Repository-relative file path"
                }
            },
            "repo_searches": {
                "type": "array",
                "description": "Used when status is 'needs_context': regex search queries across the repository to locate symbols, trait definitions, or usages. Supported: Rust / ripgrep regex syntax (lookahead/lookbehind is not supported).",
                "items": {
                    "type": "object",
                    "properties": {
                        "path": {
                            "type": "string",
                            "description": "Directory relative to repo root to scope search in (e.g. 'crates/core') or empty string for repository root"
                        },
                        "regex": {
                            "type": "string",
                            "description": "Rust / ripgrep regular expression pattern"
                        }
                    },
                    "required": ["path", "regex"],
                    "additionalProperties": false
                }
            },
            "repo_maps": {
                "type": "array",
                "description": "Used when status is 'needs_context': targeted Tree-sitter symbol contour requests for specific subsystems, each entry a repository-relative directory or file prefix (an empty string or '.' names the whole repository). Request contours when only the shape of a module is needed, or when <repo_map> does not cover that subsystem.",
                "items": {
                    "type": "string",
                    "description": "Repository-relative directory or file path"
                }
            },
            "items": {
                "type": "array",
                "description": items_description,
                "items": plan_item_schema(1, MAX_PLAN_REFINEMENT_DEPTH)
            }
        },
        "required": ["status", "explanation", "reason", "abort", "context_requests", "repo_searches", "repo_maps", "items"],
        "additionalProperties": false
    })
}

/// JSON Schema definition wrapper for provider configuration.
pub fn plan_refine_response_schema_definition() -> serde_json::Value {
    serde_json::json!({
        "name": "plan_refinement",
        "description": "Plan horizon synthesis output: the new unfinished steps or a blocker report",
        "strict": true,
        "schema": plan_refine_response_schema()
    })
}

/// Builds the unified system prompt for Architect horizon synthesis.
///
/// One prompt governs every Architect planning call — initial refinement, manual
/// re-projection, and automatic recovery after a blocked step — because all three
/// are the same operation: reprojecting the unfinished horizon from the immutable
/// concept and the completed (DONE) foundation. The prompt therefore never asks the
/// Architect to restate finished work; it demands only the new, unfinished steps.
pub fn build_plan_horizon_system_prompt() -> String {
    let mut out = String::new();
    out.push_str("You are a Principal Software Architect in TAUQE (The Answer to the Ultimate Question of Engineering).\n\n");
    out.push_str("Your mission is Wave Horizon Planning: synthesizing the entire unfinished horizon of a plan — the ordered, executable steps that still remain — from an immutable architectural concept, the completed (DONE) foundation, and, when present, the diagnostics of a blocked step.\n\n");

    out.push_str("## Core Invariants & Rules:\n\n");
    out.push_str("1. Concept Immutability (\"What\" vs \"How\"):\n");
    out.push_str("   - The architectural concept tree (`concept`) captures the developer's intent and is the immutable source of truth.\n");
    out.push_str("   - You MUST NOT alter, expand, dilute, or contradict it.\n");
    out.push_str("   - Your exclusive responsibility is engineering decomposition (\"How\"): the exact modules, interfaces, contracts, types, and sequence of implementation.\n\n");
    out.push_str("2. Horizon Synthesis Contract:\n");
    out.push_str("   - Return ONLY the new, unfinished steps of the horizon; every returned step carries `status: \"todo\"`.\n");
    out.push_str("   - Do NOT restate, re-emit, or reorder the completed (DONE) steps shown to you: the harness preserves them verbatim and concatenates them ahead of your output. Emitting a DONE step is a hard contract violation.\n");
    out.push_str("   - Reproject the WHOLE remaining horizon on every call: the horizon is a fresh, coherent plan for the remaining work, not a patch layered on an earlier draft.\n\n");
    out.push_str("3. Strict Blocker Protocol (Refusal to Plan):\n");
    out.push_str("   - If you discover an insurmountable contradiction, technical blocker, missing prerequisite, or flawed assumption in the codebase or requirements:\n");
    out.push_str("   - You MUST NOT invent a compromised, broken, or speculative plan.\n");
    out.push_str("   - You MUST set `status: \"blocked\"`, provide empty `items: []`, and document a comprehensive, rigorous technical explanation in `reason` detailing the exact contradiction, codebase evidence, and recommended developer action.\n");
    out.push_str("   - A host-environment condition only the developer can repair — a missing system utility or package, a build script awaiting approval, a stopped daemon or database, or an unauthenticated registry — is never a blocker: report it through the `abort` field with `is_aborted: true`, name the concrete missing capability in `reason`, carry the exact command the developer must run in `recommendation`, and leave `items: []`.\n\n");
    out.push_str("4. Step Granularity, Grouping and Compilability Invariants:\n");
    out.push_str("   - Execution Lifecycle Contract: EVERY leaf step is executed in an isolated turn with its own toolchain verification gates (check, clippy, test).\n");
    out.push_str("   - Disjunction Prohibition Invariant: Every concept node and every step must state exactly one definite decision, so unresolved disjunctive alternatives such as 'either X or Y' or 'use library A or write your own structure B' are strictly prohibited. The architectural choice ('What') is fixed by the concept tree and the developer, and a genuine ambiguity is reported through `status: \"blocked\"` instead of being resolved by offering alternatives; a step owns 'How' only and never decides the architecture.\n");
    out.push_str("   - Automated Verification Invariant: The harness runs full toolchain verification (compilation, linters, and tests) automatically and deterministically after every individual leaf step. Dedicated steps that only run tests, check the build status, or inspect the codebase without changing code are strictly prohibited, because the executor has no shell. Tests are created and modified inside the steps that implement the corresponding functionality.\n");
    out.push_str("   - Target File Precision (Leaf-Only Files Invariant): For every executable leaf step, you MUST populate `files: [\"path/to/file\"]` with exact repository-relative file paths. Parent items and task groups are conceptual containers and MUST have empty `files: []`. Only leaf steps (`children: []`) pre-load files into context upon execution.\n");
    out.push_str("   - Reference Files Contract (Read-Only Context): For every executable leaf step, identify and populate `readonly_files: [\"path/to/reference\"]` with existing interfaces, protocol types, or subsystem conventions needed as context during implementation. These files are pre-loaded as read-only context during step execution. Invariant: parent items must have empty `readonly_files: []`.\n");
    out.push_str("   - External Specification Contract (Outer Docs): For every executable leaf step that must be implemented against an external contract, declare the specification the project publishes in `[[outer_docs]]` through `outer_docs: [\"id\"]`, so the harness materializes it as read-only context before the step starts. One declaration names one root document and covers the whole subtree inside that root, so address a document below the root as `id/relative.md` and never climb above it. A step that carries no external dependency must use `outer_docs: []`, and a parent container item must have an empty `outer_docs: []`.\n");
    out.push_str("   - Concept Traceability: For each step, link it to the relevant architectural concept IDs via `concept_refs: [\"concept_id\"]`.\n");
    out.push_str("   - DAG Dependency Contract: For every executable leaf step, declare prerequisite step IDs in `depends_on: [\"step_id\"]`. A step runs only after every dependency reaches DONE status. Reference only steps within this horizon; steps without prerequisites must use `depends_on: []`.\n");
    out.push_str("   - Avoid Micro-Fragmentation: Strictly avoid splitting adjacent, closely related edits into separate microscopic steps. Group cohesive changes across 1-4 related files under a single leaf step if they form a logical unit of work and carry no risk of patch conflicts.\n");
    out.push_str(&format!(
        "   - Avoid Unmanageable Monoliths: Do not bundle numerous unrelated files into a single step; keep each leaf step calibrated to a cohesive unit (targeting {}-{} lines of change).\n",
        LEAF_STEP_TARGET_LINES.0, LEAF_STEP_TARGET_LINES.1
    ));
    out.push_str("   - Compilability Invariant: The codebase MUST remain in a compiling, fully verified state at the end of EVERY leaf step. Never create broken intermediate steps.\n");
    out.push_str("   - Order steps strictly by prerequisite dependencies.\n");
    out.push_str(&format!(
        "   - The plan hierarchy supports up to {} levels of nesting. Leaf steps at the maximum depth must not contain sub-items.\n\n",
        MAX_PLAN_REFINEMENT_DEPTH
    ));
    out.push_str("5. Strict Language Consistency Invariant:\n");
    out.push_str(
        "   - Detect the primary natural language used in the plan's title and description.\n",
    );
    out.push_str("   - You MUST formulate all titles, step details, explanations, and reasons strictly in that SAME natural language.\n");
    out.push_str(
        "   - Do NOT switch languages unless the plan itself is written in that language.\n\n",
    );
    out.push_str("6. Architect Research Protocol (Mandatory Contract Verification):\n");
    out.push_str("   - You have access to symbol contours in `<repo_map>` and already loaded files in `Active Context Files`.\n");
    out.push_str("   - Eager contour generation may be disabled, so `<repo_map>` can cover only part of the codebase. A module absent from the contours is never evidence that it is empty: request its contours via `repo_maps` before designing a step that touches it.\n");
    out.push_str("   - RepoMap contours are blinkers, not contracts: they reveal only the shape of the codebase (names, kinds, and rough signatures), never exact type definitions, field layouts, trait bounds, error semantics, lifetimes, or crate boundaries.\n");
    out.push_str("   - Whenever a step you synthesize must interact with an existing interface, struct, enum, function, trait, module, or external crate, you MUST NOT infer its contract from contours alone. You MUST set `status: \"needs_context\"`, request concrete source files in `context_requests: [...]`, execute regex symbol searches via `repo_searches: [{\"path\": \"...\", \"regex\": \"...\"}]`, or request Tree-sitter symbol contours of a specific subsystem via `repo_maps: [\"crates/core/src/plan\"]`, leave `items: []`, and explain in `explanation` which contracts you are verifying and why.\n");
    out.push_str("   - Contour requests (`repo_maps`) accept a repository-relative directory or file prefix; an empty string or `.` names the whole repository. They reveal module shape only, so an exact contract still has to be verified through `context_requests` or `repo_searches`.\n");
    out.push_str("   - Repository Search Syntax: searches use Rust / ripgrep regular expressions. Supported: standard character classes (\\w, \\d, \\s), boundaries (\\b, \\B), groups ((?:...)), alternation (|), and case-insensitive flags ((?i)). Lookaround assertions ((?=...), (?!...), (?<=...), (?<!...)) and backreferences are NOT supported and will trigger an error.\n");
    out.push_str("   - Never emit speculative field names, argument types, return types, generic parameters, or method signatures derived from a contour line. A guessed contract is a hard contract violation.\n");
    out.push_str("   - Do not re-request files already present in `Active Context Files`; treat them as verified context.\n");
    out.push_str("   - When all required context files are loaded and verified, set `status: \"success\"` (or `status: \"blocked\"` if blockers found), set `context_requests: []`, `repo_searches: []`, `repo_maps: []`, and provide the synthesized `items`.\n\n");
    out.push_str("7. Output Format:\n");
    out.push_str("   - Output strictly according to the specified JSON schema.\n");
    out.push_str("   - Final Content Invariant: every text field (explanation, titles, details, reason) carries only the final distilled result. The reasoning process itself is never plan content: do not record deliberation, self-questioning, exploratory analysis, or intermediate reasoning steps in any field.\n");
    out
}

/// Diagnostics describing a failed or blocked plan step that triggered horizon recovery.
///
/// The unified horizon synthesis prompt carries these diagnostics so the Architect can
/// reproject the unfinished horizon around the failure: the blocked step identifier, the
/// coder's blocker report, and the last observed toolchain status.
#[derive(Debug, Clone)]
pub struct PlanHorizonDiagnostics<'a> {
    pub blocked_step_id: &'a str,
    pub blocked_reason: Option<&'a str>,
    pub toolchain_status: Option<&'a str>,
}

/// Builds the unified user prompt for Architect horizon synthesis.
///
/// Structures the input in a fixed order: the immutable architectural concept, the
/// completed (DONE) foundation, the optional diagnostics of a blocked step, and the
/// developer's directives. The Architect returns only the NEW unfinished horizon; the
/// harness preserves the DONE foundation and concatenates it ahead of the synthesized
/// steps.
///
/// The task fragment carries domain framing only: the active context files and the
/// repository outline belong to the stable head of the round, which the turn kernel
/// renders for every contour, so a task builder never restates them.
pub fn build_plan_horizon_user_prompt(
    plan: &Plan,
    diagnostics: Option<PlanHorizonDiagnostics<'_>>,
    instructions: Option<&str>,
) -> String {
    let mut out = String::new();
    out.push_str(&format!(
        "# Plan Horizon Synthesis: [{}] {}\n\n",
        plan.id, plan.title
    ));

    if let Some(desc) = &plan.description {
        let trimmed = desc.trim();
        if !trimmed.is_empty() {
            out.push_str("## High-Level Architectural Intent (\"What\"):\n");
            out.push_str(trimmed);
            out.push_str("\n\n");
        }
    }

    if !plan.concept.is_empty() {
        out.push_str("## Architectural Concept (\"What\" - Immutable Source of Truth):\n");
        fn render_concept(out: &mut String, items: &[ConceptItem], depth: usize) {
            let indent = "  ".repeat(depth);
            for item in items {
                out.push_str(&format!("{}- **#{}** {}", indent, item.id, item.title));
                if let Some(details) = &item.details {
                    let trimmed = details.trim();
                    if !trimmed.is_empty() {
                        out.push_str(&format!(": {}", trimmed));
                    }
                }
                out.push('\n');
                render_concept(out, &item.children, depth + 1);
            }
        }
        render_concept(&mut out, &plan.concept, 0);
        out.push('\n');
    }

    out.push_str(
        "## Completed Foundation (DONE steps - immutable; do NOT repeat them in `items`):\n",
    );
    fn collect_done<'a>(items: &'a [PlanItem], acc: &mut Vec<&'a PlanItem>) {
        for item in items {
            if item.status == PlanItemStatus::Done {
                acc.push(item);
            }
            collect_done(&item.children, acc);
        }
    }
    let mut done = Vec::new();
    collect_done(&plan.items, &mut done);
    if done.is_empty() {
        out.push_str("*(No completed steps yet)*\n");
    } else {
        for item in &done {
            out.push_str(&format!("- [x] #{} {}", item.id, item.title));
            if !item.files.is_empty() {
                out.push_str(&format!(" (files: {})", item.files.join(", ")));
            }
            out.push('\n');
        }
    }
    out.push('\n');

    if let Some(diag) = diagnostics {
        out.push_str("## Blocked Step Diagnostics:\n");
        let blocked = plan.find_item(diag.blocked_step_id);
        match &blocked {
            Some(item) => out.push_str(&format!(
                "- **Blocked Step**: #{} {}\n",
                item.id, item.title
            )),
            None => out.push_str(&format!("- **Blocked Step**: #{}\n", diag.blocked_step_id)),
        }
        if let Some(item) = &blocked {
            if !item.files.is_empty() {
                out.push_str(&format!(
                    "- **Declared Target Files**: {}\n",
                    item.files.join(", ")
                ));
            }
            if let Some(details) = &item.details {
                let trimmed = details.trim();
                if !trimmed.is_empty() {
                    out.push_str(&format!("- **Declared Contract**:\n{}\n", trimmed));
                }
            }
        }
        match diag.blocked_reason.map(str::trim).filter(|s| !s.is_empty()) {
            Some(reason) => out.push_str(&format!("- **Coder Blocker Report**: {}\n", reason)),
            None => out.push_str("- **Coder Blocker Report**: (no diagnostics provided)\n"),
        }
        if let Some(status) = diag
            .toolchain_status
            .map(str::trim)
            .filter(|s| !s.is_empty())
        {
            out.push_str(&format!("- **Toolchain Status**: {}\n", status));
        }
        out.push('\n');
    }

    if let Some(ins) = instructions {
        let trimmed = ins.trim();
        if !trimmed.is_empty() {
            out.push_str("## Developer Directives:\n");
            out.push_str(trimmed);
            out.push_str("\n\n");
        }
    }

    out.push_str("## Architect Instructions:\n");
    out.push_str("1. Conduct deep technical dependency analysis using the repository outline and the loaded context files.\n");
    out.push_str("2. Synthesize the COMPLETE unfinished horizon as dependency-ordered leaf steps with `status: \"todo\"`. Do NOT include any DONE step; the harness preserves the completed foundation verbatim and prepends it.\n");
    out.push_str("3. Follow the Architect Research Protocol: before designing any step that touches an existing interface, type, trait, module, or crate, verify its real contract by requesting the relevant source files or searching for symbols via `status: \"needs_context\"` with `context_requests: [\"path/to/file\"]`, `repo_searches: [...]`, or `repo_maps: [\"path/to/module\"]`, and empty `items: []`. Never infer contracts from RepoMap contours alone.\n");
    out.push_str("4. Check for any blockers, circular dependencies, or contradictions. If blocked, report `status: \"blocked\"` with an exact `reason`.\n");
    out.push_str("5. For every executable leaf step, specify target files in `files`, reference contracts/types/conventions in `readonly_files`, external specifications the project publishes in `outer_docs` (`id` for a declared root, `id/relative.md` for a document below it), addressed concept IDs in `concept_refs`, and prerequisite step IDs in `depends_on`. Declare `outer_docs` whenever the step must be implemented against an external contract, so the harness pre-loads the specification and the executor spends no discovery round on it. Calibrate leaf step granularity to cohesive units: group closely related adjacent edits under one step to avoid micro-fragmentation, while avoiding monolithic multi-file dumps.\n");
    out.push_str("6. Disjunction Prohibition Invariant: Every concept node and every step must state exactly one definite decision, so unresolved disjunctive alternatives such as 'either X or Y' or 'use library A or write your own structure B' are strictly prohibited. The architectural choice ('What') is fixed by the concept tree and the developer, and a genuine ambiguity is reported through `status: \"blocked\"` with the exact decision the developer must make, instead of being resolved by offering alternatives; a step owns 'How' only and never decides the architecture.\n");
    out.push_str("7. Automated Verification Invariant: The harness runs full toolchain verification (compilation, linters, and tests) automatically and deterministically after every individual leaf step, so dedicated steps that only run tests, check the build status, or inspect the codebase without changing code are strictly prohibited: the executor has no shell, and tests are created and modified inside the steps that implement the corresponding functionality.\n");
    out.push_str("8. Language Directive: Detect the natural language of the plan title and description. Formulate all titles, details, explanations, and reasons strictly in that same language.\n");

    out
}

