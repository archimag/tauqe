    #[test]
    fn the_schema_requires_the_abort_escape_hatch() {
        let schema = plan_refine_response_schema();
        let abort = schema["properties"]["abort"].clone();

        // The escape hatch is the very shape the structured edit contour
        // publishes, so the two contours cannot describe different fields.
        assert_eq!(abort, crate::capabilities::abort_fragment()["abort"]);
        assert_eq!(abort["type"], "object");
        assert_eq!(abort["additionalProperties"], serde_json::json!(false));
        assert_eq!(abort["properties"]["is_aborted"]["type"], "boolean");
        assert_eq!(abort["properties"]["reason"]["type"], "string");
        assert_eq!(abort["properties"]["recommendation"]["type"], "string");

        let required = abort["required"]
            .as_array()
            .expect("the abort object requires its fields");
        let names: Vec<&str> = required.iter().filter_map(|field| field.as_str()).collect();
        assert_eq!(names, ["is_aborted", "reason", "recommendation"]);

        // The strict top-level schema demands the field, and the horizon a round
        // may carry stays empty while an abort supersedes the synthesis.
        let required: Vec<&str> = schema["required"]
            .as_array()
            .expect("the schema declares its required fields")
            .iter()
            .filter_map(|field| field.as_str())
            .collect();
        assert!(
            required.contains(&"abort"),
            "the strict schema must require the escape hatch: {required:?}"
        );
        let items = schema["properties"]["items"]["description"]
            .as_str()
            .expect("the items property declares its contract");
        assert!(items.contains("active `abort`"), "{items}");
    }

    #[test]
    fn test_parse_plan_refinement_output_decodes_the_abort_escape_hatch() {
        let active = r#"{
            "status": "blocked",
            "explanation": "The toolchain cannot run",
            "reason": null,
            "abort": {
                "is_aborted": true,
                "reason": "  clippy is not installed  ",
                "recommendation": "  rustup component add clippy  "
            },
            "context_requests": [],
            "repo_searches": [],
            "repo_maps": [],
            "items": []
        }"#;
        let parsed = parse_plan_refinement_output(active).unwrap();
        let abort = parsed.abort.expect("an active abort");
        assert!(abort.is_aborted);
        // Trimming is the decoder's duty, so the payload decodes verbatim and the
        // command side owns the normalization.
        assert_eq!(abort.reason, "  clippy is not installed  ");
        assert_eq!(abort.recommendation, "  rustup component add clippy  ");

        // The idle representation states that nothing awaits a developer action.
        let idle = r#"{
            "status": "success",
            "explanation": "Horizon synthesized",
            "reason": null,
            "abort": {"is_aborted": false, "reason": "", "recommendation": ""},
            "context_requests": [],
            "repo_searches": [],
            "repo_maps": [],
            "items": []
        }"#;
        let parsed = parse_plan_refinement_output(idle).unwrap();
        assert!(
            !parsed
                .abort
                .expect("the idle representation decodes")
                .is_aborted
        );

        // A payload written before the escape hatch existed decodes as no abort.
        let legacy = r#"{
            "status": "success",
            "explanation": "Horizon synthesized",
            "reason": null,
            "context_requests": [],
            "repo_searches": [],
            "repo_maps": [],
            "items": []
        }"#;
        assert!(parse_plan_refinement_output(legacy)
            .unwrap()
            .abort
            .is_none());
    }

