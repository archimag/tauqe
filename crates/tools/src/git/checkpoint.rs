pub const TAUQE_CO_AUTHOR_TRAILER: &str = "Co-authored-by: Tauqe AI <noreply@tauqe.dev>";
pub const CHECKPOINT_PREFIX: &str = "tauqe-checkpoint:";
pub const STEP_PREFIX: &str = "tauqe-step:";

/// Repository-relative directory holding the harness state.
///
/// The whole directory is excluded from Git. It holds the credentials file, the
/// transaction marker, the durable plan, review, history, and cached
/// documentation documents, and the staging siblings of an interrupted atomic
/// write, none of which belongs to a change set. The exclusion is installed
/// fail-closed and verified before a checkpoint commit runs.
const STATE_DIR: &str = ".tauqe";

/// On-disk marker recording an open Git transaction, relative to the repository
/// root. It lives under the gitignored `.tauqe/` directory so it never becomes
/// part of a checkpoint or step commit.
const TRANSACTION_MARKER_FILE: &str = ".tauqe/active-transaction.json";

/// Checks whether a commit was generated or co-authored by Tauqe AI.
pub fn is_tauqe_commit(subject: &str, body: &str, author: &str, trailers: &str) -> bool {
    trailers.contains("Tauqe AI")
        || trailers.contains("noreply@tauqe.dev")
        || body.contains(TAUQE_CO_AUTHOR_TRAILER)
        || body.contains("Co-authored-by: Tauqe AI")
        || body.contains("Generated by Tauqe AI")
        || author.contains("Tauqe AI")
        || author.contains("ai@tauqe.dev")
        || subject.starts_with("AI:")
        || subject.starts_with(STEP_PREFIX)
}

/// Legacy wire value an earlier revision recorded whenever `rev-parse HEAD`
/// failed on an unborn branch: the moving ref name instead of a base kind.
///
/// The marker's decode boundary maps it to [`TransactionBase::Unborn`], the
/// state it always meant, mirroring the declared-alias precedent the
/// capability tags set: an undecodable marker would hide an open
/// transaction, so markers written by earlier binaries must keep decoding.
const LEGACY_HEAD_REF: &str = "HEAD";

/// The starting point a Git transaction records and every consumer branches
/// on.
///
/// A repository whose branch already held a commit records that commit's
/// hash; a repository whose branch was unborn records the unborn state
/// itself. A consumer therefore distinguishes the two with an explicit match
/// instead of a string comparison: the earlier revision recorded the moving
/// ref `HEAD` here, which no consumer could resolve or tell apart from a
/// commit hash.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum TransactionBase {
    /// The hash of the commit the transaction started from.
    Commit(String),
    /// The branch held no commit at all when the transaction opened.
    ///
    /// An unborn base always implies `created_checkpoint_commit == false`: a
    /// clean tree is what opens it, and a dirty tree would have produced the
    /// root checkpoint commit, whose hash the marker records instead.
    Unborn,
}

impl Serialize for TransactionBase {
    /// A commit base serializes as its hash string and an unborn base as
    /// `null`, both under the preserved `previous_head` key of
    /// [`CheckpointInfo`], so the on-disk marker keeps the shape every
    /// reader already knows.
    fn serialize<S>(&self, serializer: S) -> Result<S::Ok, S::Error>
    where
        S: Serializer,
    {
        match self {
            TransactionBase::Commit(head) => serializer.serialize_str(head),
            TransactionBase::Unborn => serializer.serialize_none(),
        }
    }
}

impl<'de> Deserialize<'de> for TransactionBase {
    /// Decodes every wire form a marker ever carried: a real hash becomes
    /// [`TransactionBase::Commit`], and both `null` and the legacy `HEAD`
    /// literal become [`TransactionBase::Unborn`].
    fn deserialize<D>(deserializer: D) -> Result<Self, D::Error>
    where
        D: Deserializer<'de>,
    {
        match Option::<String>::deserialize(deserializer)? {
            None => Ok(TransactionBase::Unborn),
            Some(head) if head == LEGACY_HEAD_REF => Ok(TransactionBase::Unborn),
            Some(head) => Ok(TransactionBase::Commit(head)),
        }
    }
}

/// The phase of the capture a transaction marker records.
///
/// A dirty-tree checkpoint writes the marker twice: once before the developer's
/// work is committed, and once after the checkpoint commit exists. The phase is
/// what tells a reader which of the two writes it observes, so the marker
/// describes a running transaction as faithfully as a settled one.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum TransactionPhase {
    /// The capture is in progress: the marker is durable, but the developer's
    /// work has not been committed into a checkpoint commit yet.
    Capturing,
    /// The capture is settled: the transaction state the marker records is
    /// final and survives without a later rewrite.
    #[default]
    Established,
}

/// Checkpoint information representing saved pre-edit developer state.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct CheckpointInfo {
    pub created_checkpoint_commit: bool,
    /// The base the transaction started from, serialized under the key
    /// earlier revisions already wrote.
    #[serde(rename = "previous_head")]
    pub base: TransactionBase,
    /// The phase the marker was written in.
    ///
    /// A marker written by an earlier revision carries no such key, so a
    /// missing `phase` decodes as [`TransactionPhase::Established`] and keeps
    /// the meaning that revision gave it.
    #[serde(default)]
    pub phase: TransactionPhase,
    /// The process id of the writer that opened the transaction.
    ///
    /// `Some` names the harness process that wrote this marker, so a later
    /// reader can ask whether that writer still runs. `None` names a marker
    /// written by an earlier revision, which recorded no writer at all and
    /// therefore proves nothing about ownership.
    #[serde(default)]
    pub writer_pid: Option<u32>,
}

/// Resolves the path of the transaction marker for the given repository root.
fn transaction_marker_path(dir: &Path) -> PathBuf {
    dir.join(TRANSACTION_MARKER_FILE)
}

/// Reports whether `ancestor` is part of the history of `descendant`.
///
/// Both revisions are addressed explicitly, so the check answers about the
/// commit a proof was settled over instead of the moving `HEAD`.
fn is_ancestor_of(dir: &Path, ancestor: &str, descendant: &str, deadline: &GitDeadline) -> bool {
    run_git_with_deadline(
        Some(dir),
        &["merge-base", "--is-ancestor", ancestor, descendant],
        deadline,
    )
    .is_ok()
}

/// Lists the full hashes of every commit `rev_range` resolves to.
///
/// A range that resolves to no commit — an exhausted `{base}..HEAD` range —
/// answers with an empty list, which is the one legitimately empty answer. A
/// failed invocation propagates Git's diagnostic instead: the listing is the
/// Tauqe-trailer proof recovery settles a transaction on, so a range that
/// cannot be listed must refuse recovery rather than authorize it.
fn commit_listing(dir: &Path, rev_range: &str, deadline: &GitDeadline) -> Result<Vec<String>> {
    let listing = run_git_with_deadline(Some(dir), &["log", "--format=%H", rev_range], deadline)?;
    Ok(listing
        .lines()
        .map(|line| line.trim().to_string())
        .filter(|line| !line.is_empty())
        .collect())
}

/// Renders the refusal of a settled transaction whose proof range could not be
/// listed.
///
/// A transient or structural `git log` failure says nothing about the commits
/// a transaction recorded, so it never enters the trailer proof as an empty
/// range: recovery keeps the marker, rewrites no history, and a later startup
/// retries the proof once the range can be listed.
fn proof_listing_refusal(rev_range: &str, error: &anyhow::Error) -> String {
    format!(
        "Skipped crash recovery: the proof range {rev_range} could not be listed \
         ({error}); repository left untouched."
    )
}

/// Persists the checkpoint of an open transaction so crash recovery can tell a
/// genuine interrupted Tauqe transaction apart from an unrelated commit that
/// merely shares the step-commit subject prefix.
///
/// The marker is the single artifact that authorizes history-rewriting
/// recovery, so it is persisted through the crate's atomic-write policy end to
/// end: the directories a first write needs are created durably, with the
/// parent of every created directory synced, so a fresh `.tauqe/` entry is
/// durable in the repository root before the marker exists; the document is
/// then staged in a sibling file, synced, renamed into place, and its parent
/// directory synced. A crash or a concurrently running recovery pass
/// therefore observes either the previous complete marker or the new complete
/// marker, never a truncated or empty document that `read_transaction_marker`
/// would decode as `None` and thereby hide an open transaction.
///
/// Both writes of a capture go through this function: the marker that precedes
/// the checkpoint commit and the marker that records it. The document therefore
/// states the phase of the transaction at every instant, so no ordering of the
/// commit and the marker can leave captured work behind a marker that does not
/// name it.
fn write_transaction_marker(dir: &Path, checkpoint: &CheckpointInfo) -> Result<()> {
    let path = transaction_marker_path(dir);
    if let Some(parent) = path.parent() {
        crate::atomic_write::create_dir_all_durable(parent).with_context(|| {
            format!(
                "Failed to create transaction marker directory: {:?}",
                parent
            )
        })?;
    }
    let json =
        serde_json::to_string(checkpoint).context("Failed to serialize transaction marker")?;
    crate::atomic_write::write_atomic(&path, json.as_bytes())
        .with_context(|| format!("Failed to write transaction marker: {:?}", path))?;
    Ok(())
}

/// Durably removes the transaction marker once a transaction is committed,
/// rolled back, or recovered.
///
/// The removal runs through the durable removal barrier of the crate's
/// atomic-write policy, which syncs the directory that recorded the unlink, so
/// a crash or a power loss after the harness returned cannot resurrect a marker
/// it already cleared. That durability guards the single artifact that
/// authorizes history rewriting: a resurrected marker would let recovery prove
/// a settled transaction against the delivered squash commit, whose trailer it
/// carries, and reset the finished work away. A marker that is already absent
/// is success, and a removal that cannot be proven durable is reported instead
/// of discarded.
fn clear_transaction_marker(dir: &Path) -> Result<()> {
    let path = transaction_marker_path(dir);
    crate::atomic_write::remove_atomic(&path)
        .with_context(|| format!("Failed to clear transaction marker: {:?}", path))
}

/// Reads the transaction marker left behind by an interrupted transaction.
fn read_transaction_marker(dir: &Path) -> Option<CheckpointInfo> {
    let content = std::fs::read_to_string(transaction_marker_path(dir)).ok()?;
    serde_json::from_str(&content).ok()
}

/// Reads the subject line of one specific commit.
///
/// The evidence is read from the commit the caller pinned, never from the moving
/// `HEAD`, so a proof computed over it cannot observe a commit that landed after
/// the pin was taken.
fn commit_subject(dir: &Path, commit: &str, deadline: &GitDeadline) -> String {
    run_git_with_deadline(Some(dir), &["log", "-1", "--format=%s", commit], deadline)
        .unwrap_or_default()
        .trim()
        .to_string()
}
/// Reports whether one specific commit carries the Tauqe co-author trailer.
///
/// The probe answers about the commit it is handed, never about the moving
/// `HEAD`, so a proof computed over a pinned commit observes exactly that
/// commit. Both the settled-transaction proof of crash recovery and the base
/// return of finalization read their range through this one helper, so the two
/// can never disagree about which commits the harness created. A probe Git
/// cannot answer reports no trailer, which refuses a commit the proof cannot
/// vouch for.
fn commit_carries_tauqe_trailer(dir: &Path, commit: &str, deadline: &GitDeadline) -> bool {
    let trailers = run_git_with_deadline(
        Some(dir),
        &[
            "log",
            "-1",
            "--format=%(trailers:key=Co-authored-by)",
            commit,
        ],
        deadline,
    )
    .unwrap_or_default();
    trailers.contains("Tauqe AI")
}
/// Resolves the full hash of the commit currently checked out.
///
/// An unborn branch holds no commit to resolve, which is the `None` answer.
fn resolve_head(dir: &Path, deadline: &GitDeadline) -> Option<String> {
    run_git_with_deadline(
        Some(dir),
        &["rev-parse", "--verify", "--quiet", "HEAD"],
        deadline,
    )
    .ok()
    .map(|head| head.trim().to_string())
    .filter(|head| !head.is_empty())
}

/// Resolves the parent of one specific commit.
///
/// A repository-root commit and a revision that does not resolve both answer
/// with `None`.
fn commit_parent(dir: &Path, commit: &str, deadline: &GitDeadline) -> Option<String> {
    let revision = format!("{commit}^");
    run_git_with_deadline(
        Some(dir),
        &["rev-parse", "--verify", "--quiet", revision.as_str()],
        deadline,
    )
    .ok()
    .map(|parent| parent.trim().to_string())
    .filter(|parent| !parent.is_empty())
}

/// A refused rewrite: the repository no longer resolves the pinned identity.
///
/// A drift is a proof outcome, not a Git failure. It travels as a typed error
/// so a caller can tell the two apart: crash recovery reports the drift as its
/// skip diagnostic and keeps the marker for a later startup, while a genuine
/// Git failure keeps propagating.
#[derive(Debug)]
struct HeadDrift {
    /// The identity a proof was settled over.
    pinned: Option<String>,
    /// The identity the repository resolved instead.
    observed: Option<String>,
}

impl HeadDrift {
    /// Renders the drift as the skip diagnostic of crash recovery.
    fn skip_diagnostic(&self) -> String {
        format!(
            "Skipped crash recovery: HEAD moved from {} to {} while the transaction was being \
             proven; repository left untouched and the transaction marker is preserved for a \
             later startup.",
            describe_identity(self.pinned.as_deref()),
            describe_identity(self.observed.as_deref()),
        )
    }
}

impl std::fmt::Display for HeadDrift {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(
            f,
            "Refusing to rewrite history: HEAD moved from the pinned commit {} to {}; \
             repository left untouched",
            describe_identity(self.pinned.as_deref()),
            describe_identity(self.observed.as_deref()),
        )
    }
}

impl std::error::Error for HeadDrift {}

/// Renders a resolved identity for a diagnostic: a commit hash or the unborn
/// state.
fn describe_identity(identity: Option<&str>) -> &str {
    identity.unwrap_or("the unborn state")
}

/// The drift of the repository against a pinned identity, when it moved.
///
/// `pinned` is the identity a proof was settled over: a commit hash, or `None`
/// for a branch that held no commit. `None` is an identity like any other, so
/// a branch that gained a commit since the proof has drifted exactly as a moved
/// `HEAD` has.
fn pinned_identity_drift(
    dir: &Path,
    pinned: Option<&str>,
    deadline: &GitDeadline,
) -> Option<HeadDrift> {
    let observed = resolve_head(dir, deadline);
    if observed.as_deref() == pinned {
        return None;
    }
    Some(HeadDrift {
        pinned: pinned.map(str::to_string),
        observed,
    })
}

/// Fails when the commit `HEAD` currently names is not the pinned commit.
///
/// A proof is computed over one commit identity, and the destructive step it
/// authorizes has to act on that same commit. Re-asserting the identity
/// immediately before the step turns a `HEAD` that moved in between into a typed
/// refusal that rewrites no history, no index entry, and no working-tree byte,
/// instead of a silent destruction of a commit no proof ever saw.
fn assert_head_pinned(dir: &Path, pinned: &str, deadline: &GitDeadline) -> Result<()> {
    match pinned_identity_drift(dir, Some(pinned), deadline) {
        None => Ok(()),
        Some(drift) => Err(anyhow::Error::new(drift)),
    }
}

/// Unwinds the temporary checkpoint commit a transaction marker records.
///
/// The subject prefix identifies a commit shaped like a temporary checkpoint,
/// but it never authorizes removing that commit from the branch: a hand-written
/// commit and a checkpoint commit a developer kept after a refused recovery
/// carry the same subject, and dropping either of them rewrites history nobody
/// asked to rewrite. Authorization therefore comes from the recorded
/// transaction base alone. A settled transaction records the checkpoint commit
/// it created, so HEAD must resolve to exactly that commit. A capturing
/// transaction records the revision the capture started from, so the checkpoint
/// commit it created is the parent of HEAD. An unborn base held no commit at
/// all, so the checkpoint commit it created is the repository root.
///
/// A commit no recorded base accounts for is refused, and the branch, the
/// index, and the working tree stay exactly as they are.
///
/// A checkpoint opened on an unborn branch becomes the repository root commit,
/// so `HEAD~1` does not resolve and resetting to it would fail after the caller
/// has already replaced the working tree. The unwind therefore recognizes a
/// parentless checkpoint and returns the branch to the unborn state instead:
/// the branch ref is deleted through the conditional `update-ref -d` and the
/// index is cleared, which leaves the checkpoint's files in the working tree
/// exactly as they were before the turn — untracked on an unborn branch — while
/// the temporary commit stops being reachable.
///
/// Every piece of evidence is read from one pinned commit identity instead of
/// the moving `HEAD`: the subject, the parent, and the recorded base the proof
/// matches. That identity is re-asserted immediately before the destructive
/// step, so a `HEAD` that moved while the unwind was resolved refuses the
/// rewrite instead of dropping a commit no recorded base accounts for. Only a
/// genuine Git failure — the detected drift included — propagates.
pub fn unwind_checkpoint_if_present(dir: &Path, checkpoint: &CheckpointInfo) -> Result<bool> {
    let deadline = GitDeadline::default();
    unwind_checkpoint_if_present_with_deadline(dir, checkpoint, &deadline)
}

/// The pinned identity an authorized checkpoint unwind acts on.
///
/// The proof and the destructive step are separate units, so the action can
/// re-assert the identity the proof settled on and a test can drive them across
/// a `HEAD` that moved in between.
struct PinnedUnwind {
    /// The commit `HEAD` resolved to when the unwind was authorized.
    head: String,
    /// The parent of that commit, or `None` when it is a repository root.
    parent: Option<String>,
}

/// Resolves the checkpoint commit an unwind would remove, pinned to one identity.
///
/// `None` reports that there is nothing to unwind: the branch is unborn, the
/// commit `HEAD` names is not a temporary checkpoint, or the recorded base does
/// not account for it under the rules of [`recorded_base_authorizes_unwind`].
/// Every answer is computed from the one commit `HEAD` resolved to at entry, so a
/// commit landing afterwards can never change what the proof observes.
fn resolve_pinned_unwind(
    dir: &Path,
    checkpoint: &CheckpointInfo,
    deadline: &GitDeadline,
) -> Option<PinnedUnwind> {
    let head = resolve_head(dir, deadline)?;
    if !commit_subject(dir, &head, deadline).starts_with(CHECKPOINT_PREFIX) {
        return None;
    }
    let parent = commit_parent(dir, &head, deadline);
    if !recorded_base_authorizes_unwind(checkpoint, &head, parent.as_deref()) {
        return None;
    }
    Some(PinnedUnwind { head, parent })
}

/// Unwinds the checkpoint commit an authorization pinned, after re-asserting it.
///
/// The destructive step acts on the pinned identity alone: a parented checkpoint
/// resets to the explicit pinned parent instead of the moving `HEAD~1`, and a
/// parentless root checkpoint deletes the branch ref through the conditional
/// `update-ref -d HEAD <pinned>`, which Git refuses as soon as `HEAD` no longer
/// names that commit. The index is cleared only after the deletion was accepted.
fn unwind_pinned_head(dir: &Path, pinned: &PinnedUnwind, deadline: &GitDeadline) -> Result<()> {
    assert_head_pinned(dir, &pinned.head, deadline)?;
    match &pinned.parent {
        Some(parent) => {
            run_git_with_deadline(Some(dir), &["reset", parent.as_str()], deadline)
                .context("Failed to unwind temporary checkpoint commit")?;
        }
        None => {
            run_git_with_deadline(
                Some(dir),
                &["update-ref", "-d", "HEAD", pinned.head.as_str()],
                deadline,
            )
            .context("Failed to delete the branch ref of a root checkpoint commit")?;
            run_git_with_deadline(Some(dir), &["read-tree", "--empty"], deadline)
                .context("Failed to clear the index of a root checkpoint commit")?;
        }
    }
    Ok(())
}

/// Unwinds the temporary checkpoint commit a transaction marker records, under
/// the supplied wall-clock budget.
fn unwind_checkpoint_if_present_with_deadline(
    dir: &Path,
    checkpoint: &CheckpointInfo,
    deadline: &GitDeadline,
) -> Result<bool> {
    match resolve_pinned_unwind(dir, checkpoint, deadline) {
        Some(pinned) => {
            unwind_pinned_head(dir, &pinned, deadline)?;
            Ok(true)
        }
        None => Ok(false),
    }
}

/// Reports whether the recorded transaction base accounts for the pinned commit.
///
/// This is the only proof that authorizes a history rewrite, so every shape a
/// marker can record is matched explicitly against the pinned commit and its
/// pinned parent, and anything else answers `false`.
fn recorded_base_authorizes_unwind(
    checkpoint: &CheckpointInfo,
    head: &str,
    parent: Option<&str>,
) -> bool {
    match &checkpoint.base {
        TransactionBase::Commit(base) if checkpoint.created_checkpoint_commit => head == base,
        TransactionBase::Commit(base) => parent == Some(base.as_str()),
        TransactionBase::Unborn => parent.is_none(),
    }
}

/// The pinned identity an authorized return to the unborn state acts on.
///
/// The tracked paths travel beside the commit they were listed from, so the
/// removal can only ever touch the tree the proof observed.
struct PinnedUnbornReturn {
    /// The commit `HEAD` resolved to when the return began.
    head: String,
    /// The repository-relative paths that commit's tree tracks.
    tracked: Vec<String>,
}

/// Resolves what a return to the unborn state would remove, pinned to one identity.
///
/// `None` reports a branch that already holds no commit, which is the state the
/// return leaves behind. The tracked paths are listed from the pinned commit, so
/// a commit landing afterwards can neither widen nor shift the set.
fn resolve_pinned_unborn_return(
    dir: &Path,
    deadline: &GitDeadline,
) -> Result<Option<PinnedUnbornReturn>> {
    let Some(head) = resolve_head(dir, deadline) else {
        return Ok(None);
    };
    let listing = run_git_with_deadline(
        Some(dir),
        &["ls-tree", "-r", "--name-only", "-z", head.as_str()],
        deadline,
    )
    .context("Failed to list the paths tracked by the transaction")?;
    let tracked = listing
        .split('\0')
        .filter(|entry| !entry.is_empty())
        .map(|entry| entry.to_string())
        .collect();
    Ok(Some(PinnedUnbornReturn { head, tracked }))
}

/// Returns the branch to the unborn state an authorization pinned.
///
/// The ref deletion is conditional on the pinned commit, so a `HEAD` that moved
/// after the paths were listed refuses the rewrite before a single path leaves
/// the working tree. Only an accepted deletion clears the index and removes the
/// pinned tree's paths; untracked files the transaction never committed survive,
/// mirroring what `reset --hard` leaves alone on a born base.
fn return_pinned_to_unborn(
    dir: &Path,
    pinned: &PinnedUnbornReturn,
    deadline: &GitDeadline,
) -> Result<()> {
    assert_head_pinned(dir, &pinned.head, deadline)?;
    run_git_with_deadline(
        Some(dir),
        &["update-ref", "-d", "HEAD", pinned.head.as_str()],
        deadline,
    )
    .context("Failed to delete the branch ref of an unborn base")?;
    run_git_with_deadline(Some(dir), &["read-tree", "--empty"], deadline)
        .context("Failed to clear the index of an unborn base")?;
    for entry in &pinned.tracked {
        let target = dir.join(entry);
        let _ = std::fs::remove_file(&target);
        crate::atomic_write::prune_empty_parents(dir, &target);
    }
    Ok(())
}

/// Returns a branch that holds commits to the unborn state.
///
/// An unborn base has no commit to reset to, so returning the tree to it is its
/// own operation, resolved and acted on through one pinned identity
/// ([`resolve_pinned_unborn_return`] and [`return_pinned_to_unborn`]): the paths
/// the pinned commit's tree tracks are collected, the branch ref is deleted
/// conditionally on that commit, the index is emptied, exactly those paths are
/// removed from the working tree, and the directories their removal emptied are
/// pruned. Untracked files the transaction never committed survive, mirroring
/// what `reset --hard` leaves alone on a born base.
///
/// A branch that is already unborn changes nothing, so the helper is safe
/// whatever state a crash left behind.
fn return_to_unborn(dir: &Path, deadline: &GitDeadline) -> Result<()> {
    match resolve_pinned_unborn_return(dir, deadline)? {
        Some(pinned) => return_pinned_to_unborn(dir, &pinned, deadline),
        None => Ok(()),
    }
}

/// Scans the worktree for orphaned staging artifacts (`*.tauqe-tmp` and
/// `*.tauqe-bak`) left behind by interrupted or crashed edit commits, cleaning
/// them up or restoring original files if interrupted before the new file
/// could be renamed into place.
///
/// A sibling is reclaimed only when the writer that created it is provably
/// gone, so a sweep never disturbs a commit another process is still
/// publishing.
///
/// The walk descends one directory level at a time and asks Git to classify
/// the next level in one batched `git check-ignore` probe, so a directory the
/// ignore rules cover is never entered. A staging sibling only ever appears
/// next to a path a change set was admitted to write, and admission refuses
/// every ignored path, so a build, dependency, or generated tree holds no
/// artifact this sweep would reclaim, while entering it would stat every entry
/// of that tree at every recovery and every rollback.
///
/// The walk stops at `.git` and at the harness state directory, whose live
/// contents only the bounded companion `cleanup_state_dir_staging_files` may
/// inspect.
pub fn cleanup_orphaned_staging_files(root: &Path) -> usize {
    let mut cleaned = 0;
    let mut level = vec![root.to_path_buf()];

    while !level.is_empty() {
        let mut next_level = Vec::new();
        for current_dir in &level {
            cleaned += reclaim_in_directory(current_dir, &mut next_level);
        }
        level = prune_ignored_directories(root, next_level);
    }

    cleaned
}

/// Reclaims the staging siblings of one directory and collects the
/// subdirectories the sweep descends into next.
///
/// A symbolic link is classified, never followed, and the repository metadata
/// directory and the harness state directory are never entered.
fn reclaim_in_directory(current_dir: &Path, next_level: &mut Vec<PathBuf>) -> usize {
    let mut cleaned = 0;
    let entries = match std::fs::read_dir(current_dir) {
        Ok(entries) => entries,
        Err(_) => return cleaned,
    };

    for entry in entries.filter_map(|entry| entry.ok()) {
        let path = entry.path();
        let file_type = match entry.file_type() {
            Ok(file_type) => file_type,
            Err(_) => continue,
        };

        if file_type.is_symlink() {
            continue;
        }

        if file_type.is_dir() {
            let file_name = entry.file_name();
            if file_name == ".git" || file_name == ".tauqe" {
                continue;
            }
            next_level.push(path);
        } else if file_type.is_file() {
            let file_name = entry.file_name();
            let name = file_name.to_string_lossy();
            if reclaim_staging_sibling(&path, current_dir, &name) {
                cleaned += 1;
            }
        }
    }

    cleaned
}

/// Keeps the sweep directories Git does not ignore and drops the rest.
///
/// One batched `git check-ignore` call classifies the whole level, so a build,
/// dependency, or generated tree is pruned before it is entered instead of
/// walking every entry inside it. A candidate is addressed with a trailing
/// separator, so a directory-only rule such as `target/` matches it, and every
/// verdict echoes the probe that named the candidate it covers.
///
/// A level Git cannot classify keeps its whole set. An absent repository, an
/// unavailable `git`, or an unreadable index must never make the sweep skip a
/// directory that may hold a staging sibling, so the degraded answer restores
/// the whole-tree reach the sweep had before it asked.
fn prune_ignored_directories(root: &Path, candidates: Vec<PathBuf>) -> Vec<PathBuf> {
    if candidates.is_empty() {
        return candidates;
    }

    let probes: Vec<Option<String>> = candidates
        .iter()
        .map(|path| path.strip_prefix(root).ok().map(repository_relative_probe))
        .collect();
    let request: Vec<String> = probes.iter().flatten().cloned().collect();
    let ignored = match run_git_check_ignore(root, &request) {
        Ok(ignored) => ignored,
        Err(error) => {
            tracing::debug!(
                "Git could not classify the sweep directories, walking the whole level: {}",
                error
            );
            return candidates;
        }
    };
    if ignored.is_empty() {
        return candidates;
    }

    let mut kept = Vec::with_capacity(candidates.len());
    for (path, probe) in candidates.into_iter().zip(probes) {
        let covered = match probe {
            Some(probe) => ignored.contains(&probe),
            None => false,
        };
        if !covered {
            kept.push(path);
        }
    }
    kept
}

/// Renders a repository-relative directory as the probe `git check-ignore`
/// expects: forward slashes and a trailing separator.
fn repository_relative_probe(relative: &Path) -> String {
    let mut probe = String::new();
    for component in relative.components() {
        if let std::path::Component::Normal(part) = component {
            if !probe.is_empty() {
                probe.push('/');
            }
            probe.push_str(&part.to_string_lossy());
        }
    }
    probe.push('/');
    probe
}

/// The writer recorded in a transaction marker or a staging sibling, when that
/// writer provably still runs.
///
/// Both ownership decisions of this module ask this one question, so the marker
/// gate and the sibling sweep cannot drift. Recovery may act on a transaction
/// only when the writer that opened it can never publish it: another process
/// mid-capture, mid-step, or mid-finalization must not have its marker cleared,
/// its branch reset, or its checkpoint commit unwound. Reclamation may touch a
/// sibling only on the same terms: deleting a live writer's staged content, or
/// moving its live backup aside, corrupts the commit the sibling exists to
/// protect.
///
/// The probe is conservative, so a writer that still runs — or cannot be proven
/// dead — owns what it recorded, and a platform without a process probe reports
/// every attributed writer as live. A record of the earlier revisions, which
/// names no writer at all, proves nothing about ownership and keeps the
/// previous behavior of both paths.
fn live_writer(writer_pid: Option<u32>) -> Option<u32> {
    writer_pid.filter(|&pid| is_process_alive(pid))
}

/// Reclaims one staging sibling and reports whether anything changed.
///
/// A sibling name carries a process id and a sequence number, so the parsers
/// match the marker rather than an exact file name and keep recognizing the
/// earlier fixed-name artifacts as well. A sibling is reclaimable only when the
/// writer that created it is provably gone, so the artifacts of a concurrent
/// writer survive the sweep. A name that parses as a staging temp sibling holds
/// content staged for a rename that never happened, so nothing will read it
/// again and the file is removed. A name that parses as a staging backup
/// sibling holds the original content of a commit that stopped halfway: it is
/// moved back into place while the target is absent, and dropped once the
/// target already carries content. The restore-versus-yield decision is one
/// atomic step owned by the crate's atomic-write policy, so a target a
/// concurrent writer publishes inside the window keeps its content instead of
/// being replaced by the stale backup. An unexpected failure leaves the
/// sibling for a later sweep.
fn reclaim_staging_sibling(path: &Path, dir: &Path, name: &str) -> bool {
    if let Some(sibling) = staging_temp_sibling(name) {
        return live_writer(sibling.owner_pid).is_none() && std::fs::remove_file(path).is_ok();
    }
    if let Some(sibling) = staging_backup_sibling(name) {
        if live_writer(sibling.owner_pid).is_some() {
            return false;
        }
        let target = dir.join(sibling.original);
        return match move_without_replace(path, &target) {
            Ok(NoReplaceMove::Moved) => true,
            // A destination that already exists belongs to a writer that
            // published it, so the stale backup name is dropped while the live
            // content survives.
            Ok(NoReplaceMove::Occupied) => std::fs::remove_file(path).is_ok(),
            Err(error) => {
                tracing::debug!(
                    "Kept the staging backup sibling {} for a later sweep: {}",
                    path.display(),
                    error
                );
                false
            }
        };
    }
    false
}

/// Reclaims staging artifacts inside the harness state directory.
///
/// The worktree walk deliberately stops at the state directory, because it
/// holds live harness state — credentials, the transaction marker, and the
/// regular plan, review, history, and cached documentation documents — that no
/// sweep may touch. The atomic replacement that persists
/// those documents stages its payload inside this same directory, so a crashed
/// write leaves an orphan the worktree walk cannot reach. This bounded
/// companion walks the state directory with the same discipline and reclaims
/// only the names that parse as staging siblings of a writer that is provably
/// gone, which keeps every regular document out of the candidate set. A missing
/// state directory reclaims nothing.
fn cleanup_state_dir_staging_files(root: &Path) -> usize {
    let mut cleaned = 0;
    let mut dirs_to_visit = vec![root.join(STATE_DIR)];

    while let Some(current_dir) = dirs_to_visit.pop() {
        let entries = match std::fs::read_dir(&current_dir) {
            Ok(entries) => entries,
            Err(_) => continue,
        };

        for entry in entries.filter_map(|entry| entry.ok()) {
            let path = entry.path();
            let file_type = match entry.file_type() {
                Ok(file_type) => file_type,
                Err(_) => continue,
            };

            if file_type.is_symlink() {
                continue;
            }

            if file_type.is_dir() {
                dirs_to_visit.push(path);
            } else if file_type.is_file() {
                let file_name = entry.file_name();
                let name = file_name.to_string_lossy();
                if reclaim_staging_sibling(&path, &current_dir, &name) {
                    cleaned += 1;
                }
            }
        }
    }

    cleaned
}

/// The index lock of the repository, resolved through Git.
///
/// The lock does not always live at `<repository>/.git/index.lock`: a linked
/// worktree keeps its own index beside its private Git directory, and a
/// repository Git addresses through another layout moves it elsewhere again.
/// Git answers where its index lock lives, so the path is never derived from a
/// guess.
///
/// The answer is relative to the directory the child ran in — the repository
/// root the caller supplied — while an absolute answer replaces it, which is
/// how [`Path::join`] treats the two. A repository Git cannot inspect answers
/// `None`, and the caller then treats the repository as holding no lock it may
/// reclaim.
fn index_lock_path(dir: &Path) -> Option<PathBuf> {
    // The probe that locates the lock runs under the crate's default budget:
    // the caller's budget is the subject of the staleness question, so an
    // exhausted one would tear the probe down before it could answer where
    // the lock lives.
    let deadline = GitDeadline::default();
    let args = ["rev-parse", "--git-path", "index.lock"];
    let resolved = run_git_with_deadline(Some(dir), &args, &deadline).ok()?;
    let trimmed = resolved.trim();
    if trimmed.is_empty() {
        return None;
    }
    Some(dir.join(trimmed))
}

/// The longest lifetime a legitimate Git invocation may give an index lock.
///
/// Every Git child runs under a wall-clock budget and receives the termination
/// grace period to release its locks before it is killed outright, so a lock
/// older than the sum of the two cannot belong to an invocation that still
/// runs: the executor would have torn that invocation down already.
fn index_lock_lifetime(deadline: &GitDeadline) -> Duration {
    Duration::from_secs(deadline.timeout_secs()) + TERMINATION_GRACE
}

/// How long the index lock has existed, derived from its modification time.
///
/// Git creates the lock when its invocation starts and removes it when the
/// invocation ends, so a surviving lock dates from inside the invocation that
/// left it behind. An unreadable or future-dated timestamp proves nothing and
/// answers `None`.
fn index_lock_age(lock: &Path) -> Option<Duration> {
    std::fs::metadata(lock)
        .ok()?
        .modified()
        .ok()?
        .elapsed()
        .ok()
}

/// Removes the index lock and reports whether it existed.
///
/// A lock that is already absent is the state a completed invocation leaves
/// behind, so nothing was reclaimed. Every other failure is reported to the
/// journal and answers the same way: reclaiming an artifact never fails the
/// recovery that runs it, and the Git command the surviving lock obstructs
/// reports the real reason on its own. A reclaimed lock is recorded at `warn`
/// level, because it reports a process that died holding the repository index.
fn remove_index_lock(lock: &Path, reason: &str) -> bool {
    match std::fs::remove_file(lock) {
        Ok(()) => {
            tracing::warn!(
                path = %lock.display(),
                reason = %reason,
                "removed an orphaned Git index lock"
            );
            true
        }
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => false,
        Err(error) => {
            tracing::warn!(
                path = %lock.display(),
                reason = %error,
                "kept an orphaned Git index lock that could not be removed"
            );
            false
        }
    }
}

/// Removes an orphaned index lock that outlived every invocation that could
/// own it, and reports whether one was reclaimed.
///
/// A Git invocation torn down between creating the lock and removing it leaves
/// the lock behind, and every later invocation of the same repository then
/// fails on it. A crashed harness cannot clean up after itself, so the
/// surviving lock has to be reclaimed by the next one.
///
/// Removal rests on age alone, because no marker names the writer of a plain
/// Git invocation: a lock older than one wall-clock budget plus the
/// termination grace period cannot belong to an invocation that still runs,
/// since the executor tears down every child that reaches that age. A younger
/// lock may belong to a live invocation — another harness process, a developer
/// command, or a repository hook — so it is left untouched whatever holds it.
///
/// A repository Git cannot inspect, an unreadable timestamp, and a lock a
/// concurrent process removed first all answer `false`: the caller learns that
/// no orphan was reclaimed, never that the repository is unusable.
pub fn recover_stale_index_lock(dir: &Path, deadline: &GitDeadline) -> bool {
    matches!(
        index_availability(dir, deadline),
        IndexAvailability::Reclaimed
    )
}

/// Whether the repository index can be locked by a Git invocation right now.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum IndexAvailability {
    /// No lock file covers the index.
    Free,
    /// A lock outlived every invocation that could own it and was removed, so
    /// the index is free again.
    Reclaimed,
    /// A lock is young enough that a running invocation may still own it; the
    /// value is how long it has existed.
    Held(Duration),
}

/// Reports whether the repository index can be locked right now, reclaiming a
/// lock that no running invocation may still own.
///
/// This is the one implementation of the staleness question
/// [`recover_stale_index_lock`] answers, so an entry point that is about to
/// write the index shares it instead of restating the rule.
pub fn index_availability(dir: &Path, deadline: &GitDeadline) -> IndexAvailability {
    let Some(lock) = index_lock_path(dir) else {
        return IndexAvailability::Free;
    };
    let Some(age) = index_lock_age(&lock) else {
        return IndexAvailability::Free;
    };
    if age <= index_lock_lifetime(deadline) {
        return IndexAvailability::Held(age);
    }
    let reason = format!(
        "it outlived the {}-second Git budget and the termination grace period",
        deadline.timeout_secs()
    );
    if remove_index_lock(&lock, &reason) {
        return IndexAvailability::Reclaimed;
    }
    // The removal may have lost a race with a process that released the lock
    // itself, so the surviving state decides what the caller may do.
    match index_lock_age(&lock) {
        Some(age) => IndexAvailability::Held(age),
        None => IndexAvailability::Free,
    }
}

/// Removes the index lock the recorded transaction writer left behind and
/// reports whether one was reclaimed.
///
/// The ownership gate of [`recover_interrupted_workflow`] proves the writer
/// that opened the transaction gone before this point, so the lock that writer
/// held belongs to no process that could remove it: a writer that no longer
/// runs can never clean up after itself, while the recovery commands that
/// record the index would all fail on the surviving lock.
///
/// The proof here is the writer's death rather than the lock's age, because a
/// startup recovery may run long before the budget the age rule requires has
/// passed while the marker already names a writer that no longer exists.
/// [`recover_stale_index_lock`] covers the invocation no marker ever named.
fn recover_orphaned_index_lock(dir: &Path, writer_pid: u32) -> bool {
    let Some(lock) = index_lock_path(dir) else {
        return false;
    };
    remove_index_lock(
        &lock,
        &format!("the transaction writer (pid {writer_pid}) no longer runs"),
    )
}

/// What the sweeps performed ahead of recovery reclaimed from the repository.
///
/// Recovery resolves one of several shapes, and every settled shape reports
/// what it cleaned up. Both reclamations therefore travel together, so no
/// branch can forget one of them, and a repository that lost nothing renders
/// no diagnostic at all.
#[derive(Debug, Clone, Copy)]
struct ReclaimedOrphans {
    /// Staging siblings reclaimed by the worktree and state-directory sweeps.
    staging_files: usize,
    /// Set once the orphaned lock of the transaction writer was removed.
    index_lock: bool,
}

impl ReclaimedOrphans {
    /// Reports whether the sweeps reclaimed nothing at all.
    fn is_empty(self) -> bool {
        self.staging_files == 0 && !self.index_lock
    }

    /// Renders the reclaimed artifacts as the object of "cleaned up".
    fn clause(self) -> String {
        let mut parts = Vec::new();
        if self.staging_files > 0 {
            parts.push(format!(
                "{} orphaned staging artifact(s)",
                self.staging_files
            ));
        }
        if self.index_lock {
            parts.push("1 orphaned Git index lock".to_string());
        }
        parts.join(" and ")
    }
}

/// Appends the artifacts a recovery reclaimed to a recovery message.
fn with_reclaimed_orphans(message: &str, reclaimed: ReclaimedOrphans) -> String {
    if reclaimed.is_empty() {
        return message.to_string();
    }
    format!("{message}, cleaned up {}", reclaimed.clause())
}

/// Returns the index of an interrupted capture to the recorded base.
///
/// The capture stages the developer's work with `git add -A` before the
/// checkpoint commit records it, so a crash between the two leaves that work
/// in the index while HEAD still names the recorded base. Clearing the marker
/// alone would report a complete restoration while the index kept the staged
/// capture: the next plain `git commit` would publish work the developer never
/// staged, and the next checkpoint would see a dirty tree this turn produced.
/// The index therefore returns to the recorded base — a mixed reset for a born
/// base, and an emptied index for an unborn one, which holds no commit to
/// reset to. Both commands write the index alone, so every byte of the
/// developer's work stays in the working tree.
fn unstage_interrupted_capture(
    dir: &Path,
    base: &TransactionBase,
    deadline: &GitDeadline,
) -> Result<()> {
    match base {
        TransactionBase::Commit(base) => {
            run_git_with_deadline(Some(dir), &["reset", "--mixed", base], deadline).context(
                "Failed to unstage the capture an interrupted transaction left in the index",
            )?;
        }
        TransactionBase::Unborn => {
            run_git_with_deadline(Some(dir), &["read-tree", "--empty"], deadline)
                .context("Failed to clear the index of a capture interrupted on an unborn base")?;
        }
    }
    Ok(())
}

/// The diagnostic a capturing transaction reports when the repository state
/// matches neither recoverable shape of an interrupted capture.
const CAPTURE_MISMATCH_REFUSAL: &str =
    "Skipped crash recovery: the capturing transaction does not match the repository state; repository left untouched.";

/// Recovers a transaction whose marker still records the capturing phase.
///
/// The identity is resolved once here and the whole classification is settled
/// over it, so the recovery acts on the commit the capture was proven against
/// instead of the moving `HEAD`.
fn recover_capturing_transaction(
    dir: &Path,
    checkpoint: &CheckpointInfo,
    reclaimed: ReclaimedOrphans,
    deadline: &GitDeadline,
) -> Result<Option<String>> {
    let pinned = resolve_head(dir, deadline);
    recover_capturing_transaction_pinned(dir, checkpoint, pinned.as_deref(), reclaimed, deadline)
}

/// Recovers a capturing transaction against one pinned identity.
///
/// A capturing marker is durable before the developer's work becomes a
/// checkpoint commit, so a crash leaves exactly one of two recoverable states:
/// the commit never reached the pinned commit and the working tree still holds
/// every change the capture was about to record, or the commit reached it and
/// only the rewrite that records it is missing. Both states are recognized
/// against the recorded base — the pinned commit itself, or the parent of the
/// pinned checkpoint commit — and every other shape is refused, mirroring the
/// discipline of the established path.
///
/// Every action below re-asserts the pinned identity immediately before it
/// runs, so a repository that advanced after the crash is refused instead of
/// rewritten: the index is never unstaged over a commit that landed, and the
/// unwind never removes a checkpoint commit a later commit already descends
/// from. A drift refusal preserves the marker for a later startup.
///
/// A failure to unwind the checkpoint commit or to clear the marker propagates
/// with the marker left in place, so a later startup resolves the same state
/// again instead of continuing on top of an open transaction.
fn recover_capturing_transaction_pinned(
    dir: &Path,
    checkpoint: &CheckpointInfo,
    pinned: Option<&str>,
    reclaimed: ReclaimedOrphans,
    deadline: &GitDeadline,
) -> Result<Option<String>> {
    let subject = match pinned {
        Some(head) => commit_subject(dir, head, deadline),
        None => String::new(),
    };
    let head_is_checkpoint = pinned.is_some() && subject.starts_with(CHECKPOINT_PREFIX);
    let checkpoint_parent = match pinned {
        Some(head) if head_is_checkpoint => commit_parent(dir, head, deadline),
        _ => None,
    };

    // The capture crashed before it committed, so the working tree still holds
    // the developer's changes while the marker and the staged work of the
    // interrupted `git add -A` are stale.
    let crashed_before_commit = match &checkpoint.base {
        TransactionBase::Commit(base) => pinned == Some(base.as_str()),
        TransactionBase::Unborn => pinned.is_none(),
    };
    if crashed_before_commit {
        if let Some(drift) = pinned_identity_drift(dir, pinned, deadline) {
            return Ok(Some(drift.skip_diagnostic()));
        }
        unstage_interrupted_capture(dir, &checkpoint.base, deadline)?;
        clear_transaction_marker(dir)?;
        return Ok(Some(with_reclaimed_orphans(
            "Closed an interrupted capture: no checkpoint commit was created, the working tree was left untouched, and the index was returned to the recorded base",
            reclaimed,
        )));
    }

    // The capture committed, but crashed before the rewrite that records it.
    // The commit's parent pins it to the recorded base, so a checkpoint commit
    // produced against another revision is never mistaken for this one.
    let crashed_after_commit = head_is_checkpoint
        && match &checkpoint.base {
            TransactionBase::Commit(base) => checkpoint_parent.as_deref() == Some(base.as_str()),
            // The checkpoint commit of an unborn base is the repository root.
            TransactionBase::Unborn => checkpoint_parent.is_none(),
        };
    if crashed_after_commit {
        if let Some(drift) = pinned_identity_drift(dir, pinned, deadline) {
            return Ok(Some(drift.skip_diagnostic()));
        }
        match unwind_checkpoint_if_present_with_deadline(dir, checkpoint, deadline) {
            Ok(true) => {}
            // The unwind resolves the identity once more before it rewrites
            // anything, so a state it cannot prove on its own terms leaves the
            // marker for a later startup instead of claiming a recovery.
            Ok(false) => return Ok(Some(CAPTURE_MISMATCH_REFUSAL.to_string())),
            Err(error) => {
                if let Some(drift) = error.downcast_ref::<HeadDrift>() {
                    return Ok(Some(drift.skip_diagnostic()));
                }
                return Err(error)
                    .context("Failed to unwind the checkpoint commit of an interrupted capture");
            }
        }
        clear_transaction_marker(dir)?;
        return Ok(Some(with_reclaimed_orphans(
            "Recovered interrupted capture: unwound the checkpoint commit and returned the captured work to the working tree",
            reclaimed,
        )));
    }

    Ok(Some(CAPTURE_MISMATCH_REFUSAL.to_string()))
}

/// Recovers repository state from an interrupted/crashed workflow.
///
/// Recovery is driven strictly by the on-disk transaction marker written when a
/// checkpoint is opened. Without that marker the repository is left untouched,
/// so an unrelated commit that merely shares the `tauqe-step:` subject prefix —
/// a hand-written commit or a step commit from another branch after a checkout —
/// is never mistaken for a dangling transaction.
///
/// A marker whose phase is still `capturing` describes a crash inside the
/// capture itself, before the rewrite that records the checkpoint commit, so
/// it is resolved against HEAD and the recorded base instead of a commit
/// range.
///
/// When a settled marker is present, the whole proof is computed over one
/// identity: `HEAD` is resolved once, and every evidence step addresses that
/// pinned commit instead of the moving ref. Every commit the transaction
/// recorded on top of its base must carry the Tauqe co-author trailer — for a
/// born base, the commits between the base and the pinned commit, with the base
/// still an ancestor of it; for an unborn base, every commit reachable from the
/// pinned commit. A range that cannot be listed refuses the same way, with the
/// marker preserved and no history rewritten, while an unborn `HEAD` —
/// distinguished by resolving `HEAD`, never by a failed listing — is the one
/// legitimately empty range. A foreign commit in the range refuses recovery and
/// reports the reason instead of rewriting history. The identity is re-asserted
/// immediately before every action the proof licenses, so a repository that
/// advanced while the proof ran is refused instead of rewritten: a commit that
/// landed in between is never destroyed by a reset or by a return to the unborn
/// state no trailer check ever saw. A successful recovery returns the tree to
/// the recorded base and unwinds a temporary checkpoint commit so uncommitted
/// developer changes are restored safely.
///
/// A marker that names a writer which is provably gone also authorizes
/// reclaiming the index lock that writer left behind, because every recovery
/// command that records the index would fail on the orphaned
/// `.git/index.lock` the dead writer never removed.
///
/// Startup owns no turn context, so every Git command of the recovery runs
/// under the default wall-clock budget.
pub fn recover_interrupted_workflow(dir: &Path) -> Result<Option<String>> {
    if !crate::git::state::is_git_repository(Some(dir)) {
        return Ok(None);
    }
    let deadline = GitDeadline::default();

    let cleaned_artifacts =
        cleanup_orphaned_staging_files(dir) + cleanup_state_dir_staging_files(dir);

    let checkpoint = match read_transaction_marker(dir) {
        Some(checkpoint) => checkpoint,
        None => {
            if cleaned_artifacts > 0 {
                return Ok(Some(format!(
                    "Cleaned up {} orphaned staging artifact(s).",
                    cleaned_artifacts
                )));
            }
            return Ok(None);
        }
    };

    // The marker names the process that opened the transaction, so a writer
    // that still runs owns it: the capturing refresh, the settled trailer
    // proof, the reset to a born base, the return to an unborn base, and the
    // checkpoint unwind all act on a transaction another process is still
    // driving. The gate therefore sits ahead of the phase dispatch and refuses
    // like the other unproven branches, so the marker survives for a later
    // startup that observes an exited writer. A marker that names no writer —
    // one written by an earlier revision — proves nothing about ownership and
    // recovers as before.
    if let Some(writer_pid) = live_writer(checkpoint.writer_pid) {
        return Ok(Some(format!(
            "Skipped crash recovery: the transaction writer (pid {writer_pid}) is still running; repository left untouched."
        )));
    }

    // A writer that is provably gone cannot still hold the index lock it may
    // have left behind, and every recovery command that records the index
    // would fail on the surviving lock. The reclaim runs beside the staging
    // sweep and rests on the same ownership gate: only a marker that names a
    // writer which no longer runs authorizes it, while a marker of an earlier
    // revision, which names no writer at all, keeps the previous behavior.
    let reclaimed = ReclaimedOrphans {
        staging_files: cleaned_artifacts,
        index_lock: match checkpoint.writer_pid {
            Some(writer_pid) => recover_orphaned_index_lock(dir, writer_pid),
            None => false,
        },
    };

    // A capturing marker describes a crash inside the capture itself: the
    // developer's work may or may not have reached a checkpoint commit, and no
    // rewrite has recorded the outcome yet. The phase therefore selects the
    // recovery, because the established proof below authorizes history
    // rewriting only for a settled transaction.
    match checkpoint.phase {
        TransactionPhase::Capturing => {
            return recover_capturing_transaction(dir, &checkpoint, reclaimed, &deadline);
        }
        TransactionPhase::Established => {}
    }

    // The whole proof is settled over one resolved identity. HEAD is resolved
    // exactly once here, so every evidence step below addresses that same
    // commit and the action the proof licenses can re-assert it immediately
    // before it runs.
    let pinned = resolve_head(dir, &deadline);

    // Collect the commits the transaction recorded on top of its base. They
    // must all be Tauqe-created; anything else means this is not a dangling
    // Tauqe transaction and must be left alone. A range that cannot be listed
    // refuses recovery instead of entering the proof as an empty one, because
    // the absence of evidence is not the evidence of an empty transaction.
    let commits = match &checkpoint.base {
        TransactionBase::Commit(base) => {
            // The recorded base must still be part of the history of the
            // pinned commit. After a manual branch switch the base can belong
            // to another branch entirely, and resetting to it would discard
            // commits that were never part of the transaction.
            match pinned.as_deref() {
                Some(pinned_commit) if is_ancestor_of(dir, base, pinned_commit, &deadline) => {
                    let rev_range = format!("{base}..{pinned_commit}");
                    match commit_listing(dir, &rev_range, &deadline) {
                        Ok(commits) => commits,
                        Err(error) => return Ok(Some(proof_listing_refusal(&rev_range, &error))),
                    }
                }
                _ => {
                    return Ok(Some(format!(
                        "Skipped crash recovery: recorded transaction base {base} is not an ancestor of HEAD; repository left untouched."
                    )));
                }
            }
        }
        // An unborn base held no commit at all, so every commit reachable
        // from the pinned commit was recorded by the transaction and enters
        // the proof. An unborn pinned HEAD holds no range to list, so it is
        // the one legitimately empty proof range; a pinned HEAD that resolves
        // holds commits and has to be listed like any other proof range.
        TransactionBase::Unborn => match pinned.as_deref() {
            None => Vec::new(),
            Some(pinned_commit) => match commit_listing(dir, pinned_commit, &deadline) {
                Ok(commits) => commits,
                Err(error) => return Ok(Some(proof_listing_refusal(pinned_commit, &error))),
            },
        },
    };
    for commit in &commits {
        if !commit_carries_tauqe_trailer(dir, commit, &deadline) {
            return Ok(Some(format!(
                "Skipped crash recovery: commit {} in the recorded transaction range was not created by Tauqe AI; repository left untouched.",
                commit
            )));
        }
    }

    settle_proved_transaction(
        dir,
        &checkpoint,
        pinned.as_deref(),
        commits.len(),
        reclaimed,
        &deadline,
    )
}

/// Acts on a transaction whose proof is settled, refusing a moved repository.
///
/// The proof itself — the resolved identity, the listed commits, and their
/// trailer verification — is computed by the caller over one pinned commit.
/// Every action below re-asserts that identity immediately before it runs, so a
/// repository that advanced while the proof was being settled is refused with
/// the skip diagnostic instead of rewritten: a commit no trailer check ever saw
/// is never destroyed by the reset or by the return to the unborn state.
///
/// Once the tree sits at the recorded base, the tolerance contract of a
/// completed recovery applies: a failure to unwind the checkpoint commit or to
/// clear the marker is reported in the diagnostic instead of aborting, because
/// a later startup resolves the same state idempotently.
fn settle_proved_transaction(
    dir: &Path,
    checkpoint: &CheckpointInfo,
    pinned: Option<&str>,
    unwound_steps: usize,
    reclaimed: ReclaimedOrphans,
    deadline: &GitDeadline,
) -> Result<Option<String>> {
    // If there were no step commits and no checkpoint commit created, there is
    // no transaction state to unwind. Resetting --hard in this case would
    // destroy legitimate uncommitted working tree changes. Closing the
    // transaction still acts on the proven state, so the pinned identity is
    // re-asserted before the marker is cleared.
    if unwound_steps == 0 && !checkpoint.created_checkpoint_commit {
        if let Some(drift) = pinned_identity_drift(dir, pinned, deadline) {
            return Ok(Some(drift.skip_diagnostic()));
        }
        clear_transaction_marker(dir)?;
        if reclaimed.is_empty() {
            return Ok(None);
        }
        return Ok(Some(format!("Cleaned up {}.", reclaimed.clause())));
    }

    // Return the tree to the recorded base and unwind a temporary checkpoint
    // commit so the developer's uncommitted changes return to the working
    // tree. A born base resets to the recorded commit; an unborn base holds no
    // commit to reset to, so the branch returns to the unborn state and
    // exactly the paths the transaction tracked leave the working tree. Both
    // leave untracked files alone, matching the previous recovery semantics.
    if let Some(drift) = pinned_identity_drift(dir, pinned, deadline) {
        return Ok(Some(drift.skip_diagnostic()));
    }
    match &checkpoint.base {
        TransactionBase::Commit(base) => {
            run_git_with_deadline(Some(dir), &["reset", "--hard", base], deadline)
                .context("Failed to reset to the recorded transaction base")?;
        }
        TransactionBase::Unborn => match return_to_unborn(dir, deadline) {
            Ok(()) => {}
            Err(error) => {
                // The return resolves and re-asserts its own pinned identity, so
                // a repository that moved inside that window is refused here
                // with the same diagnostic, while a genuine Git failure
                // propagates.
                if let Some(drift) = error.downcast_ref::<HeadDrift>() {
                    return Ok(Some(drift.skip_diagnostic()));
                }
                return Err(error).context("Failed to return the branch to its unborn base");
            }
        },
    }
    // The reset above has already replaced the pre-turn working tree, so a
    // failure to unwind the checkpoint commit must not abort with the marker
    // left behind: every later startup would fail identically and the
    // developer's work would stay stranded inside the checkpoint commit. The
    // failure is reported in the diagnostic instead, and the marker is cleared
    // so recovery completes.
    let mut unwind_error = None;
    if checkpoint.created_checkpoint_commit {
        if let Err(err) = unwind_checkpoint_if_present_with_deadline(dir, checkpoint, deadline) {
            tracing::error!(
                "Failed to unwind the checkpoint commit during recovery: {}",
                err
            );
            unwind_error = Some(err);
        }
    }
    // The reset above has already returned the tree to the recorded base, so a
    // failure to clear the marker must not abort with the recovered tree left
    // behind a marker that still records an open transaction: the failure is
    // reported in the diagnostic instead, and the surviving marker makes the
    // next startup retry a recovery that is idempotent once the tree already
    // sits at the recorded base.
    let clear_error = match clear_transaction_marker(dir) {
        Ok(()) => None,
        Err(err) => {
            tracing::error!(
                "Failed to clear the transaction marker during recovery: {}",
                err
            );
            Some(err)
        }
    };

    let mut msg = format!(
        "Recovered interrupted workflow: unwound {} step commit(s), restored checkpoint: {}",
        unwound_steps, checkpoint.created_checkpoint_commit
    );
    if !reclaimed.is_empty() {
        msg.push_str(&format!(", cleaned up {}", reclaimed.clause()));
    }
    if let Some(err) = unwind_error {
        msg.push_str(&format!(
            ", but the checkpoint commit could not be unwound ({err}); the pre-turn work \
             stays recoverable inside the `{CHECKPOINT_PREFIX}` commit at HEAD"
        ));
    }
    if let Some(err) = clear_error {
        msg.push_str(&format!(
            ", but the transaction marker could not be cleared ({err}); a later startup \
             retries the recovery"
        ));
    }
    Ok(Some(msg))
}

/// Returns the ignore rules that hide the harness state and the credentials.
///
/// The whole state directory is excluded, so nothing the harness persists there
/// — the credentials file, the transaction marker, the durable plan, review,
/// history, and cached documentation documents, and the staging siblings of an
/// interrupted atomic write — can reach a checkpoint commit. The credential
/// files at the repository root are named explicitly, and the two staging
/// suffixes keep a crashed write out of the index until recovery reclaims it.
///
/// Every staging rule is derived from the marker constant that owns its
/// spelling, so the exclusion installed here, the sibling-name parsers, and
/// crash recovery name one set of artifacts: a marker the atomic-write policy
/// renames can never leave the siblings it produces outside the rules.
fn tauqe_ignore_rules() -> Vec<String> {
    vec![
        format!("{STATE_DIR}/"),
        format!("{STATE_DIR}/credentials.toml"),
        "credentials.toml".to_string(),
        ".credentials.toml".to_string(),
        format!("*{STAGING_TEMP_MARKER}*"),
        format!("*{STAGING_BACKUP_MARKER}*"),
    ]
}

/// Ensures that the harness state and the credential files are ignored by Git in
/// the repository's local exclude configuration (`.git/info/exclude`),
/// protecting them without modifying tracked project files.
///
/// A rule written by an earlier revision is left in place: within one exclude
/// file a later rule overrides an earlier one, and a repeated run recognises the
/// rules of the scheme it wrote instead of appending them a second time.
///
/// The complete document is published in a single atomic replacement, so the
/// multi-writer model the ownership gates declare cannot interleave two
/// installations: an application that appended each rule on its own `O_APPEND`
/// handle wrote the pattern bytes and the trailing newline of one rule as
/// distinct syscalls, and two such writers could fuse two rules into one
/// meaningless line or tear one apart. An interrupted replacement leaves the
/// previous complete document in place, and a run that finds every rule already
/// declared writes nothing at all.
pub fn ensure_tauqe_ignored(dir: &Path) -> Result<()> {
    let deadline = GitDeadline::default();
    ensure_tauqe_ignored_with_deadline(dir, &deadline)
}

/// Applies the same installation under the supplied wall-clock budget.
fn ensure_tauqe_ignored_with_deadline(dir: &Path, deadline: &GitDeadline) -> Result<()> {
    let git_dir_res = run_git_with_deadline(Some(dir), &["rev-parse", "--git-dir"], deadline);
    if let Ok(git_dir_str) = git_dir_res {
        let trimmed = git_dir_str.trim();
        if !trimmed.is_empty() {
            let git_dir = if Path::new(trimmed).is_absolute() {
                PathBuf::from(trimmed)
            } else {
                dir.join(trimmed)
            };
            let info_dir = git_dir.join("info");
            let exclude_path = info_dir.join("exclude");
            crate::atomic_write::create_dir_all_durable(&info_dir).with_context(|| {
                format!("Failed to create the Git info directory: {:?}", info_dir)
            })?;
            let content = std::fs::read(&exclude_path).unwrap_or_default();
            if let Some(document) = exclusion_document(&content, &tauqe_ignore_rules()) {
                crate::atomic_write::write_atomic(&exclude_path, &document).with_context(|| {
                    format!("Failed to publish the Git exclude file: {:?}", exclude_path)
                })?;
            }

            // Publishing a pattern does not prove that Git honours it: a project
            // `.gitignore` outranks `.git/info/exclude` and can re-include a
            // protected path, and a path already in the index is never ignored.
            verify_protected_paths_ignored(dir, deadline)?;
        }
    }
    Ok(())
}

/// Builds the complete exclusion document, or reports that nothing is missing.
///
/// A document that already declares every rule answers with `None`, so a
/// repeated installation leaves the file untouched instead of rewriting
/// identical bytes. Otherwise the existing content is carried over verbatim, one
/// separator newline closes it exactly when it is non-empty and lacks a
/// terminator, and every missing rule follows newline-terminated.
///
/// The content travels as bytes, so an exclude file this process cannot decode
/// keeps every byte it carries; the rule recognition runs over a lossy view,
/// where an undecodable line simply declares no rule.
fn exclusion_document(existing: &[u8], rules: &[String]) -> Option<Vec<u8>> {
    let declared = String::from_utf8_lossy(existing);
    let missing: Vec<&String> = rules
        .iter()
        .filter(|rule| {
            !declared
                .lines()
                .any(|line| declares_rule(line, rule.as_str()))
        })
        .collect();
    if missing.is_empty() {
        return None;
    }

    let missing_bytes: usize = missing.iter().map(|rule| rule.len() + 1).sum();
    let mut document = Vec::with_capacity(existing.len() + 1 + missing_bytes);
    document.extend_from_slice(existing);
    if !existing.is_empty() && !existing.ends_with(b"\n") {
        document.push(b'\n');
    }
    for rule in missing {
        document.extend_from_slice(rule.as_bytes());
        document.push(b'\n');
    }
    Some(document)
}

/// Reports whether `line` already declares `rule`, under any accepted spelling.
///
/// An exclude file a developer or an earlier revision edited may carry the rule
/// with a leading or a trailing separator, and both spellings cover the same
/// paths. Recognising them keeps a repeated installation from appending a
/// duplicate rule beside the equivalent one.
fn declares_rule(line: &str, rule: &str) -> bool {
    let trimmed = line.trim();
    trimmed == rule
        || trimmed == format!("{rule}/")
        || trimmed == format!("/{rule}")
        || trimmed == format!("/{rule}/")
}

/// Repository-relative paths a checkpoint commit must never stage.
///
/// The credential paths hold the OpenRouter API key, while the transaction
/// marker and the staging representatives name the harness state and the
/// artifacts of an interrupted atomic replacement. A temporary commit that
/// includes any of them keeps it in the object database and the reflog long
/// after the checkpoint is unwound. Rolling history back does not remove the
/// object, and any tooling that walks dangling commits can read it.
///
/// The two staging representatives are derived from the marker constants the
/// atomic-write policy declares, so the proof names the suffixes that policy
/// really writes instead of restating them.
fn protected_paths() -> Vec<String> {
    vec![
        TRANSACTION_MARKER_FILE.to_string(),
        ".tauqe/credentials.toml".to_string(),
        "credentials.toml".to_string(),
        ".credentials.toml".to_string(),
        format!("draft.rs{STAGING_TEMP_MARKER}"),
        format!("draft.rs{STAGING_BACKUP_MARKER}"),
    ]
}

/// Fails when Git does not exclude every protected path.
///
/// `git add -A` stages everything Git does not consider ignored, so a checkpoint
/// may only be created once the ignore rules are proven to cover the protected
/// set. The proof is one batched `git check-ignore` call for the whole set, and it
/// is deliberately fail-closed: an unanswered or negative probe aborts the
/// checkpoint instead of committing a credential file or harness state into a
/// temporary commit.
fn verify_protected_paths_ignored(dir: &Path, deadline: &GitDeadline) -> Result<()> {
    let candidates = protected_paths();
    let ignored = run_git_check_ignore_with_deadline(dir, &candidates, deadline)
        .context("Failed to verify that the protected paths are ignored by Git")?;

    let leaked: Vec<&str> = candidates
        .iter()
        .map(String::as_str)
        .filter(|path| !ignored.iter().any(|entry| entry.as_str() == *path))
        .collect();

    if leaked.is_empty() {
        return Ok(());
    }

    bail!(
        "Refusing to create a checkpoint: Git does not ignore protected path(s): {}; \
         unresolvable ignore rules would commit a credential file or harness state",
        leaked.join(", ")
    );
}

/// Refuses a capture that would overwrite a live writer's transaction marker.
///
/// The marker is the single artifact crash recovery acts on, so a capture never
/// replaces one that describes a transaction another process is still
/// driving: that writer may be mid-capture, mid-step, or mid-finalization, and
/// a capture of this process would leave its work behind a marker that no
/// longer names it.
///
/// The ownership decision is the one the recovery gate and the staging-sibling
/// sweep apply, read through the same helper, and the refusal is the one an
/// isolated commit raises. A marker this process wrote itself keeps the
/// previous behavior, because no other process could have opened it; a marker
/// attributed to a provably dead writer and an unattributed legacy marker keep
/// it as well, and the first is what a startup recovery resolves.
fn refuse_owned_transaction_marker(dir: &Path) -> Result<()> {
    let Some(checkpoint) = read_transaction_marker(dir) else {
        return Ok(());
    };
    let own_pid = std::process::id();
    let Some(writer_pid) = live_writer(checkpoint.writer_pid) else {
        return Ok(());
    };
    if writer_pid == own_pid {
        return Ok(());
    }
    Err(anyhow::Error::new(LiveTransactionWriter {
        writer_pid,
        step: "open a transaction",
    }))
}

/// Creates a safe checkpoint of uncommitted changes before applying AI modifications.
///
/// A tree holding uncommitted work is captured in two phases: the marker that
/// announces the capture is made durable first, and it is rewritten once the
/// checkpoint commit records the work. A crash inside the capture is therefore
/// always described by a marker, whichever of the two writes it interrupted,
/// instead of leaving the captured work inside a commit nothing names.
///
/// `hooks` is the hook policy the temporary checkpoint commit follows.
///
/// A capture never opens over a transaction another live writer owns: the
/// existing marker refuses it before the ignore rules are installed, before the
/// repository is probed, and before the marker is written.
pub fn create_checkpoint(dir: &Path, hooks: GitHooks) -> Result<CheckpointInfo> {
    let deadline = GitDeadline::default();
    create_checkpoint_with_deadline(dir, hooks, &deadline)
}

/// Creates a safe checkpoint of uncommitted changes, under the supplied
/// wall-clock budget.
pub fn create_checkpoint_with_deadline(
    dir: &Path,
    hooks: GitHooks,
    deadline: &GitDeadline,
) -> Result<CheckpointInfo> {
    // A capture overwrites the marker, so the ownership gate runs first: the
    // refusal precedes the ignore-rule installation, the repository probes,
    // and the first marker write, leaving any live transaction exactly as it
    // was.
    refuse_owned_transaction_marker(dir)?;

    // The ignore rules are the only mechanism that keeps the credential file out
    // of `git add -A`, so a failure to install them aborts the checkpoint instead
    // of committing the API key into a temporary commit.
    ensure_tauqe_ignored_with_deadline(dir, deadline)?;

    let status =
        run_git_with_deadline(Some(dir), &["status", "--porcelain"], deadline).unwrap_or_default();
    let is_dirty = !status.trim().is_empty();

    // A resolving HEAD names the commit the transaction starts from; a failing
    // one means the branch is unborn, which the marker records as the typed
    // unborn state rather than the moving ref `HEAD`.
    let base = match run_git_with_deadline(Some(dir), &["rev-parse", "HEAD"], deadline) {
        Ok(head) => TransactionBase::Commit(head.trim().to_string()),
        Err(_) => TransactionBase::Unborn,
    };

    if !is_dirty {
        let checkpoint = CheckpointInfo {
            created_checkpoint_commit: false,
            base,
            phase: TransactionPhase::Established,
            writer_pid: Some(std::process::id()),
        };
        write_transaction_marker(dir, &checkpoint)?;
        return Ok(checkpoint);
    }

    // Announce the capture before it starts. Without this write a crash between
    // the commit below and the marker that records it would leave the captured
    // work inside a checkpoint commit that no marker authorizes recovery to
    // name.
    let capturing = CheckpointInfo {
        created_checkpoint_commit: false,
        base,
        phase: TransactionPhase::Capturing,
        writer_pid: Some(std::process::id()),
    };
    write_transaction_marker(dir, &capturing)?;

    // Stage and commit uncommitted user changes into a checkpoint commit.
    // Ignored paths (.tauqe, credentials, temporary files) in .git/info/exclude
    // are automatically skipped by git add -A without argument pathspec errors.
    run_git_with_deadline(Some(dir), &["add", "-A"], deadline)
        .context("Failed to stage uncommitted changes for checkpoint")?;

    commit_with_developer_author_with_deadline(
        dir,
        "tauqe-checkpoint: uncommitted user changes",
        false,
        hooks,
        deadline,
    )?;

    let new_head = run_git_with_deadline(Some(dir), &["rev-parse", "HEAD"], deadline)
        .unwrap_or_default()
        .trim()
        .to_string();
    // The checkpoint commit exists now, so the branch is born even where it
    // was unborn before: the recorded base is the checkpoint itself, which
    // the unwind recognizes as a parentless root commit.
    let checkpoint = CheckpointInfo {
        created_checkpoint_commit: true,
        base: TransactionBase::Commit(new_head),
        phase: TransactionPhase::Established,
        writer_pid: Some(std::process::id()),
    };
    write_transaction_marker(dir, &checkpoint)?;
    Ok(checkpoint)
}

/// Restores working tree back to pre-checkpoint state (used on workflow failure/cancellation).
pub fn restore_checkpoint(dir: &Path, checkpoint: &CheckpointInfo) -> Result<()> {
    let deadline = GitDeadline::default();
    restore_checkpoint_with_deadline(dir, checkpoint, &deadline)
}

/// Restores the working tree to the pre-checkpoint state under the supplied
/// wall-clock budget.
pub fn restore_checkpoint_with_deadline(
    dir: &Path,
    checkpoint: &CheckpointInfo,
    deadline: &GitDeadline,
) -> Result<()> {
    // 1. Return the working tree to the checkpoint base. An unborn base
    //    holds no commit to reset to, so returning the tree to it removes
    //    exactly the paths the transaction tracked and deletes the branch
    //    ref.
    match &checkpoint.base {
        TransactionBase::Commit(head) => {
            run_git_with_deadline(Some(dir), &["reset", "--hard", head], deadline)?;
        }
        TransactionBase::Unborn => return_to_unborn(dir, deadline)?,
    }
    let _ = run_git_with_deadline(
        Some(dir),
        &[
            "clean",
            "-fd",
            "-e",
            ".tauqe",
            "-e",
            "credentials.toml",
            "-e",
            ".credentials.toml",
        ],
        deadline,
    );

    // 2. Close the transaction before the checkpoint is unwound. The reset above
    //    has already replaced the pre-turn working tree, so a failed unwind must
    //    never leave the marker behind and strand every later recovery: the
    //    marker is cleared first, and the failure propagates as a diagnostic the
    //    rollback-retry loop of the engine can act on.
    clear_transaction_marker(dir)?;
    if checkpoint.created_checkpoint_commit {
        unwind_checkpoint_if_present_with_deadline(dir, checkpoint, deadline).with_context(
            || {
                format!(
                    "the working tree was reset but the `{CHECKPOINT_PREFIX}` commit could not \
                 be unwound; the pre-turn work stays recoverable inside it at HEAD"
                )
            },
        )?;
    }

    cleanup_orphaned_staging_files(dir);
    Ok(())
}

/// Creates an intermediate step commit during edit execution or verification auto-healing.
///
/// `hooks` is the hook policy the step commit follows.
pub fn create_step_commit(
    dir: &Path,
    changed_files: &[String],
    step_name: &str,
    hooks: GitHooks,
) -> Result<String> {
    let deadline = GitDeadline::default();
    create_step_commit_with_deadline(dir, changed_files, step_name, hooks, &deadline)
}

/// Creates an intermediate step commit under the supplied wall-clock budget.
pub fn create_step_commit_with_deadline(
    dir: &Path,
    changed_files: &[String],
    step_name: &str,
    hooks: GitHooks,
    deadline: &GitDeadline,
) -> Result<String> {
    if changed_files.is_empty() {
        return Ok(String::new());
    }

    stage_files_with_deadline(dir, changed_files, deadline)?;

    let commit_message = format!(
        "tauqe-step: {}\n\n{}",
        step_name.trim(),
        TAUQE_CO_AUTHOR_TRAILER
    );
    commit_with_developer_author_with_deadline(dir, &commit_message, false, hooks, deadline)?;

    let short_hash = run_git_with_deadline(Some(dir), &["rev-parse", "--short", "HEAD"], deadline)?
        .trim()
        .to_string();

    Ok(short_hash)
}

/// An open transaction that blocked a step another live writer owns.
///
/// The refusal is typed, mirroring the drift refusal of the recovery paths, so
/// a caller can tell a marker another live transaction owns apart from a Git
/// failure without inspecting an error message. `step` names the work the live
/// transaction blocked, so one type renders both the refusal of an isolated
/// commit and the refusal of a capture.
#[derive(Debug)]
struct LiveTransactionWriter {
    /// The process id the marker records as its writer.
    writer_pid: u32,
    /// The work the live transaction blocked, rendered into the refusal.
    step: &'static str,
}

impl std::fmt::Display for LiveTransactionWriter {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(
            f,
            "Refusing to {}: the transaction writer (pid {}) is still running; repository left \
             untouched and the transaction marker is preserved",
            self.step, self.writer_pid
        )
    }
}

impl std::error::Error for LiveTransactionWriter {}

/// Clears the transaction marker of a transaction the caller did not open.
///
/// An isolated commit never opens a transaction, so it may only clear a marker
/// that no live writer owns. The ownership decision is the one the recovery gate
/// and the staging-sibling sweep apply, read through the same helper: a marker
/// that is absent, a marker attributed to a provably dead writer, and an
/// unattributed legacy marker all keep the previous clearing behavior, while a
/// marker a live writer owns is preserved for the transaction that opened it,
/// which its own rollback or a later startup recovery resolves.
///
/// The gate runs before any staging and any commit, so a refusal leaves `HEAD`,
/// the index, the working tree, and the marker exactly as they were.
fn clear_unowned_transaction_marker(dir: &Path) -> Result<()> {
    if let Some(checkpoint) = read_transaction_marker(dir) {
        if let Some(writer_pid) = live_writer(checkpoint.writer_pid) {
            return Err(anyhow::Error::new(LiveTransactionWriter {
                writer_pid,
                step: "create an isolated commit",
            }));
        }
    }
    clear_transaction_marker(dir)
}

/// Closes a transaction whose change set holds no tracked path.
///
/// A bounded turn can verify cleanly while every file it wrote lives outside
/// Git: the `.tauqe/mockups/` sandbox is the documented case, because the
/// harness keeps it out of every commit. Such a turn still opened a checkpoint
/// and recorded a transaction marker, so the transaction is unwound here. The
/// checkpoint commit is rolled back into the working tree, which keeps the
/// developer's uncommitted work, and the empty hash reports that no commit was
/// created.
///
/// The marker belongs to the transaction the caller opened, so it is cleared
/// without the ownership gate an isolated commit applies.
fn close_transaction_without_changes(
    dir: &Path,
    checkpoint: &CheckpointInfo,
    deadline: &GitDeadline,
) -> Result<String> {
    if checkpoint.created_checkpoint_commit {
        let _ = unwind_checkpoint_if_present_with_deadline(dir, checkpoint, deadline)?;
    }
    clear_transaction_marker(dir)?;
    Ok(String::new())
}
/// Resolves the identity a finalization returns the branch from, proving the
/// recorded transaction base still accounts for it.
///
/// A born base is proven exactly as crash recovery proves a settled
/// transaction: the commit `HEAD` names must resolve, the recorded base must
/// still be an ancestor of it, and every commit in the `base..pinned` range must
/// carry the Tauqe co-author trailer. A range that cannot be listed refuses the
/// same way, so an unestablished listing never counts as an empty range. An
/// unborn base proves nothing here, because its branch holds no commit to
/// descend from; the pinned commit is only the target of the conditional
/// deletion the action performs.
///
/// Every refusal precedes all mutation: the branch, the index, the working
/// tree, and the transaction marker the turn opened stay exactly as they were,
/// so a commit that landed concurrently, the transaction's own commits, and the
/// artifact a later recovery needs all survive a refused finalization.
fn resolve_pinned_finalize_return(
    dir: &Path,
    checkpoint: &CheckpointInfo,
    deadline: &GitDeadline,
) -> Result<Option<String>> {
    let head = resolve_head(dir, deadline);
    let TransactionBase::Commit(base) = &checkpoint.base else {
        return Ok(head);
    };

    let Some(pinned) = head.as_deref() else {
        bail!(
            "Refusing to finalize: the recorded transaction base {base} cannot be returned to \
             because HEAD holds no commit; repository left untouched"
        );
    };
    if !is_ancestor_of(dir, base, pinned, deadline) {
        bail!(
            "Refusing to finalize: recorded transaction base {base} is not an ancestor of HEAD; \
             repository left untouched"
        );
    }
    let rev_range = format!("{base}..{pinned}");
    let commits = commit_listing(dir, &rev_range, deadline).with_context(|| {
        format!("Refusing to finalize: the proof range {rev_range} could not be listed")
    })?;
    for commit in &commits {
        if !commit_carries_tauqe_trailer(dir, commit, deadline) {
            bail!(
                "Refusing to finalize: commit {commit} in the recorded transaction range was not \
                 created by Tauqe AI; repository left untouched"
            );
        }
    }
    Ok(head)
}

/// Returns the branch to the recorded base an authorization pinned.
///
/// The born base re-asserts the pinned commit immediately before the soft
/// reset, so a `HEAD` that moved while the proof ran is a typed refusal that
/// rewrites no history, no index entry, and no working-tree byte. The unborn
/// base deletes the branch ref through the conditional `update-ref -d HEAD
/// <pinned>` form, whose `<oldvalue>` operand makes Git itself refuse the
/// deletion as soon as `HEAD` names another commit. The index is left untouched
/// either way, so the step commits stay staged work.
fn perform_pinned_finalize_return(
    dir: &Path,
    checkpoint: &CheckpointInfo,
    pinned: Option<&str>,
    deadline: &GitDeadline,
) -> Result<()> {
    match (&checkpoint.base, pinned) {
        (TransactionBase::Commit(base), Some(head)) => {
            assert_head_pinned(dir, head, deadline)?;
            run_git_with_deadline(Some(dir), &["reset", "--soft", base.as_str()], deadline)
                .context("Failed to soft reset to checkpoint base")?;
        }
        (TransactionBase::Commit(_), None) => bail!(
            "Refusing to finalize: HEAD holds no commit the recorded transaction base could be \
             returned to; repository left untouched"
        ),
        (TransactionBase::Unborn, Some(head)) => {
            run_git_with_deadline(Some(dir), &["update-ref", "-d", "HEAD", head], deadline)
                .context("Failed to soft reset to the unborn checkpoint base")?;
        }
        (TransactionBase::Unborn, None) => {}
    }
    Ok(())
}
/// Squashes all intermediate step commits into a single final AI commit.
///
/// A change set without a single tracked path — one that lives entirely in the
/// mockups sandbox — closes the open transaction and reports the absence of a
/// commit instead of failing the verified turn.
///
/// `hooks` is the hook policy the squashed commit follows.
pub fn finalize_ai_commit(
    dir: &Path,
    checkpoint: &CheckpointInfo,
    changed_files: &[String],
    summary: &str,
    hooks: GitHooks,
) -> Result<String> {
    let deadline = GitDeadline::default();
    finalize_ai_commit_with_deadline(dir, checkpoint, changed_files, summary, hooks, &deadline)
}

/// Squashes the intermediate step commits into one AI commit under the supplied
/// wall-clock budget.
///
/// The base return that opens the squash is proven and pinned before it acts:
/// the identity `HEAD` names is resolved once, the recorded base must still
/// account for it, and the destructive step re-asserts that identity before it
/// moves a ref — a conditional ref deletion for an unborn base, a re-asserted
/// soft reset for a born one. A refusal precedes all mutation, so a commit that
/// landed concurrently, the transaction's own commits, and the marker a later
/// recovery needs all survive a refused finalization.
pub fn finalize_ai_commit_with_deadline(
    dir: &Path,
    checkpoint: &CheckpointInfo,
    changed_files: &[String],
    summary: &str,
    hooks: GitHooks,
    deadline: &GitDeadline,
) -> Result<String> {
    if changed_files.is_empty() {
        return close_transaction_without_changes(dir, checkpoint, deadline);
    }

    // 1. Return the branch to the recorded base, so every step commit becomes
    //    staged work. The proof and the action are separate units: the identity
    //    is resolved and proven once, and the destructive step then acts on that
    //    pinned commit alone, exactly as the crash-recovery paths of this module
    //    do. An unborn base holds no commit to reset to: deleting the branch ref
    //    leaves the index untouched, so the step commits collapse into staged
    //    work and the final commit becomes the single squashed root instead of
    //    an empty commit on top of the last step.
    let pinned = resolve_pinned_finalize_return(dir, checkpoint, deadline)?;
    perform_pinned_finalize_return(dir, checkpoint, pinned.as_deref(), deadline)?;

    // 2. If checkpoint commit was created, unwind it so user uncommitted changes stay in working tree
    if checkpoint.created_checkpoint_commit {
        let _ = unwind_checkpoint_if_present_with_deadline(dir, checkpoint, deadline)?;
    }

    // Step commits and temporary checkpoint commits have been unwound back to the
    // working tree. Clear the transaction marker now so an error during staging
    // or committing does not leave a dangling marker that would reset --hard and
    // destroy working tree changes on startup.
    clear_transaction_marker(dir)?;

    // 3. Stage touched files
    stage_files_with_deadline(dir, changed_files, deadline)?;

    let commit_message = format!("{}\n\n{}", summary.trim(), TAUQE_CO_AUTHOR_TRAILER);
    commit_with_developer_author_with_deadline(dir, &commit_message, false, hooks, deadline)?;

    let short_hash = run_git_with_deadline(Some(dir), &["rev-parse", "--short", "HEAD"], deadline)?
        .trim()
        .to_string();

    Ok(short_hash)
}

/// Creates an isolated AI commit containing only the files modified by the model.
///
/// `hooks` is the hook policy the commit follows.
pub fn create_ai_commit(
    dir: &Path,
    changed_files: &[String],
    summary: &str,
    hooks: GitHooks,
) -> Result<String> {
    let deadline = GitDeadline::default();
    create_ai_commit_with_deadline(dir, changed_files, summary, hooks, &deadline)
}

/// Creates an isolated AI commit under the supplied wall-clock budget.
///
/// An isolated commit opens no transaction of its own, so it clears the
/// transaction marker only when no live writer owns it: a marker attributed to a
/// process that still runs refuses the commit before anything is staged, while an
/// absent marker, a marker attributed to a provably dead writer, and an
/// unattributed legacy marker keep the previous clearing behavior. A change set
/// that holds no tracked path closes the same way and reports the empty hash.
pub fn create_ai_commit_with_deadline(
    dir: &Path,
    changed_files: &[String],
    summary: &str,
    hooks: GitHooks,
    deadline: &GitDeadline,
) -> Result<String> {
    // An isolated commit holds no transaction of its own, so it may only clear a
    // marker no live writer owns. The gate runs before any staging and any
    // commit, so a refusal leaves HEAD, the index, the working tree, and the
    // marker of the open transaction untouched for its own rollback or a later
    // startup recovery.
    clear_unowned_transaction_marker(dir)?;

    if changed_files.is_empty() {
        return Ok(String::new());
    }

    // No recorded base authorizes removing a temporary checkpoint commit from
    // the branch: a commit of that shape stays in the history, exactly as a
    // hand-written one would.
    stage_files_with_deadline(dir, changed_files, deadline)?;

    let commit_message = format!("{}\n\n{}", summary.trim(), TAUQE_CO_AUTHOR_TRAILER);
    commit_with_developer_author_with_deadline(dir, &commit_message, false, hooks, deadline)?;

    let short_hash = run_git_with_deadline(Some(dir), &["rev-parse", "--short", "HEAD"], deadline)?
        .trim()
        .to_string();

    Ok(short_hash)
}

