pub const TAUQE_CO_AUTHOR_TRAILER: &str = "Co-authored-by: Tauqe AI <noreply@tauqe.dev>";
pub const CHECKPOINT_PREFIX: &str = "tauqe-checkpoint:";
pub const STEP_PREFIX: &str = "tauqe-step:";

/// Repository-relative path of the tracked external reference registry.
///
/// The ignore scheme below is the reason this path is declared here: the
/// registry is the one tracked artifact inside the harness state directory, so
/// the rules have to name it exactly to keep it reachable while every sibling
/// stays excluded. `tauqe_core::refs` re-exports the declaration as the location
/// it reads.
pub const REFS_MANIFEST: &str = ".tauqe/refs/refs.md";

/// Repository-relative directory holding the tracked registry material.
pub const REFS_DIR: &str = ".tauqe/refs";

/// On-disk marker recording an open Git transaction, relative to the repository
/// root. It lives under the gitignored `.tauqe/` directory so it never becomes
/// part of a checkpoint or step commit.
const TRANSACTION_MARKER_FILE: &str = ".tauqe/active-transaction.json";

/// Checks whether a commit was generated or co-authored by Tauqe AI.
pub fn is_tauqe_commit(subject: &str, body: &str, author: &str, trailers: &str) -> bool {
    trailers.contains("Tauqe AI")
        || trailers.contains("noreply@tauqe.dev")
        || body.contains(TAUQE_CO_AUTHOR_TRAILER)
        || body.contains("Co-authored-by: Tauqe AI")
        || body.contains("Generated by Tauqe AI")
        || author.contains("Tauqe AI")
        || author.contains("ai@tauqe.dev")
        || subject.starts_with("AI:")
        || subject.starts_with(STEP_PREFIX)
}

/// Legacy wire value an earlier revision recorded whenever `rev-parse HEAD`
/// failed on an unborn branch: the moving ref name instead of a base kind.
///
/// The marker's decode boundary maps it to [`TransactionBase::Unborn`], the
/// state it always meant, mirroring the declared-alias precedent the
/// capability tags set: an undecodable marker would hide an open
/// transaction, so markers written by earlier binaries must keep decoding.
const LEGACY_HEAD_REF: &str = "HEAD";

/// The starting point a Git transaction records and every consumer branches
/// on.
///
/// A repository whose branch already held a commit records that commit's
/// hash; a repository whose branch was unborn records the unborn state
/// itself. A consumer therefore distinguishes the two with an explicit match
/// instead of a string comparison: the earlier revision recorded the moving
/// ref `HEAD` here, which no consumer could resolve or tell apart from a
/// commit hash.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum TransactionBase {
    /// The hash of the commit the transaction started from.
    Commit(String),
    /// The branch held no commit at all when the transaction opened.
    ///
    /// An unborn base always implies `created_checkpoint_commit == false`: a
    /// clean tree is what opens it, and a dirty tree would have produced the
    /// root checkpoint commit, whose hash the marker records instead.
    Unborn,
}

impl Serialize for TransactionBase {
    /// A commit base serializes as its hash string and an unborn base as
    /// `null`, both under the preserved `previous_head` key of
    /// [`CheckpointInfo`], so the on-disk marker keeps the shape every
    /// reader already knows.
    fn serialize<S>(&self, serializer: S) -> Result<S::Ok, S::Error>
    where
        S: Serializer,
    {
        match self {
            TransactionBase::Commit(head) => serializer.serialize_str(head),
            TransactionBase::Unborn => serializer.serialize_none(),
        }
    }
}

impl<'de> Deserialize<'de> for TransactionBase {
    /// Decodes every wire form a marker ever carried: a real hash becomes
    /// [`TransactionBase::Commit`], and both `null` and the legacy `HEAD`
    /// literal become [`TransactionBase::Unborn`].
    fn deserialize<D>(deserializer: D) -> Result<Self, D::Error>
    where
        D: Deserializer<'de>,
    {
        match Option::<String>::deserialize(deserializer)? {
            None => Ok(TransactionBase::Unborn),
            Some(head) if head == LEGACY_HEAD_REF => Ok(TransactionBase::Unborn),
            Some(head) => Ok(TransactionBase::Commit(head)),
        }
    }
}

/// Checkpoint information representing saved pre-edit developer state.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct CheckpointInfo {
    pub created_checkpoint_commit: bool,
    /// The base the transaction started from, serialized under the key
    /// earlier revisions already wrote.
    #[serde(rename = "previous_head")]
    pub base: TransactionBase,
}

/// Resolves the path of the transaction marker for the given repository root.
fn transaction_marker_path(dir: &Path) -> PathBuf {
    dir.join(TRANSACTION_MARKER_FILE)
}

/// Reports whether the recorded transaction base is still part of the history of
/// the commit currently checked out.
fn is_ancestor_of_head(dir: &Path, ancestor: &str) -> bool {
    run_git(
        Some(dir),
        &["merge-base", "--is-ancestor", ancestor, "HEAD"],
    )
    .is_ok()
}

/// Lists the full hashes of every commit `rev_range` resolves to.
///
/// A range nothing resolves to answers with an empty list, so an unborn
/// branch or an exhausted range is a valid negative answer rather than a
/// failure the recovery would have to report.
fn commit_listing(dir: &Path, rev_range: &str) -> Vec<String> {
    run_git(Some(dir), &["log", "--format=%H", rev_range])
        .unwrap_or_default()
        .lines()
        .map(|line| line.trim().to_string())
        .filter(|line| !line.is_empty())
        .collect()
}

/// Persists the checkpoint of an open transaction so crash recovery can tell a
/// genuine interrupted Tauqe transaction apart from an unrelated commit that
/// merely shares the step-commit subject prefix.
///
/// The marker is the single artifact that authorizes history-rewriting
/// recovery, so it is persisted through the crate's atomic-write policy: the
/// document is staged in a sibling file, synced, renamed into place, and its
/// parent directory synced. A crash or a concurrently running recovery pass
/// therefore observes either the previous complete marker or the new complete
/// marker, never a truncated or empty document that `read_transaction_marker`
/// would decode as `None` and thereby hide an open transaction.
///
/// One ordering window remains: the checkpoint commit becomes durable before
/// the marker that records it is written. A crash between the two leaves the
/// repository holding the checkpoint commit but no marker, and recovery
/// deliberately leaves such a repository untouched because its contract
/// requires the marker as proof; the developer's captured work remains
/// recoverable inside the checkpoint commit with standard Git tooling. Writing
/// the marker before the commit was rejected deliberately: with the current
/// [`CheckpointInfo`] semantics it would open a window in which recovery
/// hard-resets the recorded base while the developer's changes sit only in the
/// index or in a commit the trailer proof does not recognize, destroying work
/// the current order always preserves.
fn write_transaction_marker(dir: &Path, checkpoint: &CheckpointInfo) -> Result<()> {
    let path = transaction_marker_path(dir);
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent).with_context(|| {
            format!(
                "Failed to create transaction marker directory: {:?}",
                parent
            )
        })?;
    }
    let json =
        serde_json::to_string(checkpoint).context("Failed to serialize transaction marker")?;
    crate::atomic_write::write_atomic(&path, json.as_bytes())
        .with_context(|| format!("Failed to write transaction marker: {:?}", path))?;
    Ok(())
}

/// Removes the transaction marker once a transaction is committed or rolled back.
fn clear_transaction_marker(dir: &Path) {
    let _ = std::fs::remove_file(transaction_marker_path(dir));
}

/// Reads the transaction marker left behind by an interrupted transaction.
fn read_transaction_marker(dir: &Path) -> Option<CheckpointInfo> {
    let content = std::fs::read_to_string(transaction_marker_path(dir)).ok()?;
    serde_json::from_str(&content).ok()
}

/// Reports whether the commit currently checked out has a parent.
///
/// An unborn branch has no commit at all and a repository-root commit has no
/// parent, so both answer negatively.
fn head_has_parent(dir: &Path) -> bool {
    run_git(Some(dir), &["rev-parse", "--verify", "--quiet", "HEAD^"]).is_ok()
}

/// Unwinds a temporary checkpoint commit at HEAD if present via mixed reset.
/// Returns true if a checkpoint commit was unwound.
///
/// A checkpoint opened on an unborn branch becomes the repository root commit,
/// so `HEAD~1` does not resolve and resetting to it would fail after the caller
/// has already replaced the working tree. The unwind therefore recognizes a
/// parentless checkpoint and returns the branch to the unborn state instead:
/// the branch ref is deleted and the index is cleared, which leaves the
/// checkpoint's files in the working tree exactly as they were before the turn —
/// untracked on an unborn branch — while the temporary commit stops being
/// reachable. Only a genuine Git failure propagates.
pub fn unwind_checkpoint_if_present(dir: &Path) -> Result<bool> {
    let head_subject = run_git(Some(dir), &["log", "-1", "--format=%s"])
        .unwrap_or_default()
        .trim()
        .to_string();
    if !head_subject.starts_with(CHECKPOINT_PREFIX) {
        return Ok(false);
    }
    if head_has_parent(dir) {
        run_git(Some(dir), &["reset", "HEAD~1"])
            .context("Failed to unwind temporary checkpoint commit")?;
    } else {
        run_git(Some(dir), &["update-ref", "-d", "HEAD"])
            .context("Failed to delete the branch ref of a root checkpoint commit")?;
        run_git(Some(dir), &["read-tree", "--empty"])
            .context("Failed to clear the index of a root checkpoint commit")?;
    }
    Ok(true)
}

/// Returns a branch that holds commits to the unborn state.
///
/// An unborn base has no commit to reset to, so returning the tree to it is
/// its own operation: the paths the transaction's history tracks are
/// collected, the branch ref is deleted, the index is emptied, exactly those
/// paths are removed from the working tree, and the directories their
/// removal emptied are pruned. Untracked files the transaction never
/// committed survive, mirroring what `reset --hard` leaves alone on a born
/// base.
///
/// A branch that is already unborn changes nothing, so the helper is safe
/// whatever state a crash left behind.
fn return_to_unborn(dir: &Path) -> Result<()> {
    if run_git(Some(dir), &["rev-parse", "--verify", "--quiet", "HEAD"]).is_err() {
        return Ok(());
    }
    let tracked = run_git(Some(dir), &["ls-tree", "-r", "--name-only", "-z", "HEAD"])
        .context("Failed to list the paths tracked by the transaction")?;
    run_git(Some(dir), &["update-ref", "-d", "HEAD"])
        .context("Failed to delete the branch ref of an unborn base")?;
    run_git(Some(dir), &["read-tree", "--empty"])
        .context("Failed to clear the index of an unborn base")?;
    for entry in tracked.split('\0').filter(|entry| !entry.is_empty()) {
        let target = dir.join(entry);
        let _ = std::fs::remove_file(&target);
        crate::atomic_write::prune_empty_parents(dir, &target);
    }
    Ok(())
}

/// Scans the worktree for orphaned staging artifacts (`*.tauqe-tmp` and
/// `*.tauqe-bak`) left behind by interrupted or crashed edit commits, cleaning
/// them up or restoring original files if interrupted before the new file
/// could be renamed into place.
///
/// A sibling is reclaimed only when the writer that created it is provably
/// gone, so a sweep never disturbs a commit another process is still
/// publishing.
///
/// The walk stops at `.git` and at the harness state directory, whose live
/// contents only the bounded companion `cleanup_state_dir_staging_files` may
/// inspect.
pub fn cleanup_orphaned_staging_files(root: &Path) -> usize {
    let mut cleaned = 0;
    let mut dirs_to_visit = vec![root.to_path_buf()];

    while let Some(current_dir) = dirs_to_visit.pop() {
        let entries = match std::fs::read_dir(&current_dir) {
            Ok(entries) => entries,
            Err(_) => continue,
        };

        for entry in entries.filter_map(|e| e.ok()) {
            let path = entry.path();
            let file_type = match entry.file_type() {
                Ok(ft) => ft,
                Err(_) => continue,
            };

            if file_type.is_symlink() {
                continue;
            }

            if file_type.is_dir() {
                let file_name = entry.file_name();
                if file_name == ".git" || file_name == ".tauqe" {
                    continue;
                }
                dirs_to_visit.push(path);
            } else if file_type.is_file() {
                let file_name = entry.file_name();
                let name = file_name.to_string_lossy();
                if reclaim_staging_sibling(&path, &current_dir, &name) {
                    cleaned += 1;
                }
            }
        }
    }

    cleaned
}

/// Reports whether the writer recorded in a staging sibling is provably gone.
///
/// Reclamation may touch a sibling only when the writer that created it can
/// never publish it: deleting a live writer's staged content, or moving its
/// live backup aside, corrupts the commit the sibling exists to protect. The
/// liveness probe is conservative, so a writer that still runs — or cannot be
/// proven dead — owns its siblings. A name of the earlier fixed-name policy
/// records no writer at all and keeps the previous reclaim behavior.
fn writer_is_gone(sibling: &StagingSibling<'_>) -> bool {
    match sibling.owner_pid {
        Some(pid) => !is_process_alive(pid),
        None => true,
    }
}

/// Reclaims one staging sibling and reports whether anything changed.
///
/// A sibling name carries a process id and a sequence number, so the parsers
/// match the marker rather than an exact file name and keep recognizing the
/// earlier fixed-name artifacts as well. A sibling is reclaimable only when the
/// writer that created it is provably gone, so the artifacts of a concurrent
/// writer survive the sweep. A name that parses as a staging temp sibling holds
/// content staged for a rename that never happened, so nothing will read it
/// again and the file is removed. A name that parses as a staging backup
/// sibling holds the original content of a commit that stopped halfway: it is
/// renamed back into place while the target is absent, and dropped once the
/// target already carries content.
fn reclaim_staging_sibling(path: &Path, dir: &Path, name: &str) -> bool {
    if let Some(sibling) = staging_temp_sibling(name) {
        return writer_is_gone(&sibling) && std::fs::remove_file(path).is_ok();
    }
    if let Some(sibling) = staging_backup_sibling(name) {
        if !writer_is_gone(&sibling) {
            return false;
        }
        let target = dir.join(sibling.original);
        return if target.exists() {
            std::fs::remove_file(path).is_ok()
        } else {
            std::fs::rename(path, &target).is_ok()
        };
    }
    false
}

/// Name of the harness state directory, derived from the tracked registry
/// location so the directory is never written out a second time.
fn state_dir_name() -> &'static str {
    REFS_DIR
        .split_once('/')
        .map_or(REFS_DIR, |(state_dir, _)| state_dir)
}

/// Reclaims staging artifacts inside the harness state directory.
///
/// The worktree walk deliberately stops at the state directory, because it
/// holds live harness state — credentials, the tracked reference registry, the
/// transaction marker, and the regular plan, review, history, and reference
/// documents — that no sweep may touch. The atomic replacement that persists
/// those documents stages its payload inside this same directory, so a crashed
/// write leaves an orphan the worktree walk cannot reach. This bounded
/// companion walks the state directory with the same discipline and reclaims
/// only the names that parse as staging siblings of a writer that is provably
/// gone, which keeps every regular document out of the candidate set. A missing
/// state directory reclaims nothing.
fn cleanup_state_dir_staging_files(root: &Path) -> usize {
    let mut cleaned = 0;
    let mut dirs_to_visit = vec![root.join(state_dir_name())];

    while let Some(current_dir) = dirs_to_visit.pop() {
        let entries = match std::fs::read_dir(&current_dir) {
            Ok(entries) => entries,
            Err(_) => continue,
        };

        for entry in entries.filter_map(|entry| entry.ok()) {
            let path = entry.path();
            let file_type = match entry.file_type() {
                Ok(file_type) => file_type,
                Err(_) => continue,
            };

            if file_type.is_symlink() {
                continue;
            }

            if file_type.is_dir() {
                dirs_to_visit.push(path);
            } else if file_type.is_file() {
                let file_name = entry.file_name();
                let name = file_name.to_string_lossy();
                if reclaim_staging_sibling(&path, &current_dir, &name) {
                    cleaned += 1;
                }
            }
        }
    }

    cleaned
}

/// Recovers repository state from an interrupted/crashed workflow.
///
/// Recovery is driven strictly by the on-disk transaction marker written when a
/// checkpoint is opened. Without that marker the repository is left untouched,
/// so an unrelated commit that merely shares the `tauqe-step:` subject prefix —
/// a hand-written commit or a step commit from another branch after a checkout —
/// is never mistaken for a dangling transaction.
///
/// When the marker is present, every commit the transaction recorded on top
/// of its base must carry the Tauqe co-author trailer — for a born base, the
/// commits between the base and HEAD, with the base still an ancestor of
/// HEAD; for an unborn base, every commit reachable from HEAD. Otherwise
/// recovery refuses and reports the reason instead of rewriting history. A
/// successful recovery returns the tree to the recorded base and unwinds a
/// temporary checkpoint commit so uncommitted developer changes are restored
/// safely.
pub fn recover_interrupted_workflow(dir: &Path) -> Result<Option<String>> {
    if !crate::git::state::is_git_repository(Some(dir)) {
        return Ok(None);
    }

    let cleaned_artifacts =
        cleanup_orphaned_staging_files(dir) + cleanup_state_dir_staging_files(dir);

    let checkpoint = match read_transaction_marker(dir) {
        Some(checkpoint) => checkpoint,
        None => {
            if cleaned_artifacts > 0 {
                return Ok(Some(format!(
                    "Cleaned up {} orphaned staging artifact(s).",
                    cleaned_artifacts
                )));
            }
            return Ok(None);
        }
    };

    // Collect the commits the transaction recorded on top of its base. They
    // must all be Tauqe-created; anything else means this is not a dangling
    // Tauqe transaction and must be left alone.
    let commits = match &checkpoint.base {
        TransactionBase::Commit(head) => {
            // The recorded base must still be part of the history of the
            // commit that is currently checked out. After a manual branch
            // switch the base can belong to another branch entirely, and
            // resetting to it would discard commits that were never part of
            // the transaction.
            if !is_ancestor_of_head(dir, head) {
                return Ok(Some(format!(
                    "Skipped crash recovery: recorded transaction base {head} is not an ancestor of HEAD; repository left untouched."
                )));
            }
            commit_listing(dir, &format!("{head}..HEAD"))
        }
        // An unborn base held no commit at all, so every commit reachable
        // from HEAD was recorded by the transaction and enters the proof.
        TransactionBase::Unborn => commit_listing(dir, "HEAD"),
    };
    for commit in &commits {
        let trailers = run_git(
            Some(dir),
            &[
                "log",
                "-1",
                "--format=%(trailers:key=Co-authored-by)",
                commit,
            ],
        )
        .unwrap_or_default();
        if !trailers.contains("Tauqe AI") {
            return Ok(Some(format!(
                "Skipped crash recovery: commit {} in the recorded transaction range was not created by Tauqe AI; repository left untouched.",
                commit
            )));
        }
    }

    let unwound_steps = commits.len();

    // If there were no step commits and no checkpoint commit created, there is
    // no transaction state to unwind. Resetting --hard in this case would destroy
    // legitimate uncommitted working tree changes.
    if unwound_steps == 0 && !checkpoint.created_checkpoint_commit {
        clear_transaction_marker(dir);
        if cleaned_artifacts > 0 {
            return Ok(Some(format!(
                "Cleaned up {} orphaned staging artifact(s).",
                cleaned_artifacts
            )));
        }
        return Ok(None);
    }

    // Return the tree to the recorded base and unwind a temporary checkpoint
    // commit so the developer's uncommitted changes return to the working
    // tree. A born base resets to the recorded commit; an unborn base holds
    // no commit to reset to, so the branch returns to the unborn state and
    // exactly the paths the transaction tracked leave the working tree. Both
    // leave untracked files alone, matching the previous recovery semantics.
    match &checkpoint.base {
        TransactionBase::Commit(head) => {
            run_git(Some(dir), &["reset", "--hard", head])
                .context("Failed to reset to the recorded transaction base")?;
        }
        TransactionBase::Unborn => {
            return_to_unborn(dir).context("Failed to return the branch to its unborn base")?;
        }
    }
    // The reset above has already replaced the pre-turn working tree, so a
    // failure to unwind the checkpoint commit must not abort with the marker
    // left behind: every later startup would fail identically and the
    // developer's work would stay stranded inside the checkpoint commit. The
    // failure is reported in the diagnostic instead, and the marker is cleared
    // so recovery completes.
    let mut unwind_error = None;
    if checkpoint.created_checkpoint_commit {
        if let Err(err) = unwind_checkpoint_if_present(dir) {
            tracing::error!(
                "Failed to unwind the checkpoint commit during recovery: {}",
                err
            );
            unwind_error = Some(err);
        }
    }
    clear_transaction_marker(dir);

    if unwound_steps > 0 || checkpoint.created_checkpoint_commit {
        let mut msg = format!(
            "Recovered interrupted workflow: unwound {} step commit(s), restored checkpoint: {}",
            unwound_steps, checkpoint.created_checkpoint_commit
        );
        if cleaned_artifacts > 0 {
            msg.push_str(&format!(
                ", cleaned up {} orphaned staging artifact(s)",
                cleaned_artifacts
            ));
        }
        if let Some(err) = unwind_error {
            msg.push_str(&format!(
                ", but the checkpoint commit could not be unwound ({err}); the pre-turn work \
                 stays recoverable inside the `{CHECKPOINT_PREFIX}` commit at HEAD"
            ));
        }
        Ok(Some(msg))
    } else if cleaned_artifacts > 0 {
        Ok(Some(format!(
            "Cleaned up {} orphaned staging artifact(s).",
            cleaned_artifacts
        )))
    } else {
        Ok(None)
    }
}

/// Ensures that `.tauqe` and sensitive credential/runtime files are ignored by Git in the
/// Git ignore rules that hide the harness state while keeping the tracked
/// registry reachable.
///
/// `.git/info/exclude` follows gitignore semantics: within one file the last
/// matching rule wins, and Git descends into a directory only while no rule
/// ignores it. The state directory is therefore re-included first, then the
/// registry directory, and finally the manifest file, so every level of the
/// tracked path stays reachable while each sibling under the state directory
/// stays excluded.
///
/// The state directory is derived from the manifest location instead of being
/// written out again, because a negation re-opens descent only when it names
/// the exact ancestor of the path it protects.
fn tauqe_ignore_rules() -> Vec<String> {
    let state_dir = state_dir_name();
    vec![
        format!("!{state_dir}"),
        format!("{state_dir}/*"),
        format!("!{REFS_DIR}/"),
        format!("{REFS_DIR}/*"),
        format!("!{REFS_MANIFEST}"),
        "credentials.toml".to_string(),
        ".credentials.toml".to_string(),
        "*.tauqe-tmp*".to_string(),
        "*.tauqe-bak*".to_string(),
    ]
}

/// Ensures that the harness state and sensitive credential/runtime files are
/// ignored by Git in the repository's local exclude configuration
/// (`.git/info/exclude`), protecting them without modifying tracked project
/// files.
///
/// The tracked reference registry lives inside the state directory, so the
/// rules re-include it instead of hiding the whole tree. A rule written by an
/// earlier revision is left in place: within one exclude file a later rule
/// overrides an earlier one, so the negation re-opens a directory that rule had
/// excluded and the manifest becomes trackable without rewriting the file.
pub fn ensure_tauqe_ignored(dir: &Path) -> Result<()> {
    let git_dir_res = run_git(Some(dir), &["rev-parse", "--git-dir"]);
    if let Ok(git_dir_str) = git_dir_res {
        let trimmed = git_dir_str.trim();
        if !trimmed.is_empty() {
            let git_dir = if Path::new(trimmed).is_absolute() {
                PathBuf::from(trimmed)
            } else {
                dir.join(trimmed)
            };
            let info_dir = git_dir.join("info");
            let exclude_path = info_dir.join("exclude");
            let _ = std::fs::create_dir_all(&info_dir);
            let content = std::fs::read_to_string(&exclude_path).unwrap_or_default();
            let patterns = tauqe_ignore_rules();
            let mut to_append = Vec::new();
            for pat in patterns {
                let already_ignored = content.lines().any(|line| {
                    let t = line.trim();
                    t == pat
                        || t == format!("{pat}/")
                        || t == format!("/{pat}")
                        || t == format!("/{pat}/")
                });
                if !already_ignored {
                    to_append.push(pat);
                }
            }
            if !to_append.is_empty() {
                use std::io::Write;
                let mut file = std::fs::OpenOptions::new()
                    .create(true)
                    .append(true)
                    .open(&exclude_path)
                    .with_context(|| {
                        format!("Failed to open the Git exclude file: {:?}", exclude_path)
                    })?;
                if !content.is_empty() && !content.ends_with('\n') {
                    writeln!(file)?;
                }
                for pat in to_append {
                    writeln!(file, "{pat}")?;
                }
            }

            // Appending a pattern does not prove that Git honours it: a project
            // `.gitignore` outranks `.git/info/exclude` and can re-include a
            // protected path, and a path already in the index is never ignored.
            verify_protected_paths_ignored(dir)?;
        }
    }
    Ok(())
}

/// Repository-relative paths a checkpoint commit must never stage.
///
/// They hold the OpenRouter API key, so a temporary commit that includes them
/// keeps the secret in the object database and the reflog long after the
/// checkpoint is unwound. Rolling history back does not remove the object, and
/// any tooling that walks dangling commits can read it.
const PROTECTED_PATHS: [&str; 3] = [
    ".tauqe/credentials.toml",
    "credentials.toml",
    ".credentials.toml",
];

/// Fails when Git does not exclude every protected path.
///
/// `git add -A` stages everything Git does not consider ignored, so a checkpoint
/// may only be created once the ignore rules are proven to cover the protected
/// set. The proof is one batched `git check-ignore` call for the whole set, and it
/// is deliberately fail-closed: an unanswered or negative probe aborts the
/// checkpoint instead of committing a credential file into a temporary commit.
fn verify_protected_paths_ignored(dir: &Path) -> Result<()> {
    let candidates: Vec<String> = PROTECTED_PATHS
        .iter()
        .map(|path| path.to_string())
        .collect();
    let ignored = run_git_check_ignore(dir, &candidates)
        .context("Failed to verify that the protected paths are ignored by Git")?;

    let leaked: Vec<&str> = PROTECTED_PATHS
        .iter()
        .copied()
        .filter(|path| !ignored.iter().any(|entry| entry.as_str() == *path))
        .collect();

    if leaked.is_empty() {
        return Ok(());
    }

    bail!(
        "Refusing to create a checkpoint: Git does not ignore protected path(s): {}; \
         unresolvable ignore rules would commit a credential file",
        leaked.join(", ")
    );
}

/// Creates a safe checkpoint of uncommitted changes before applying AI modifications.
///
/// `hooks` is the hook policy the temporary checkpoint commit follows.
pub fn create_checkpoint(dir: &Path, hooks: GitHooks) -> Result<CheckpointInfo> {
    // The ignore rules are the only mechanism that keeps the credential file out
    // of `git add -A`, so a failure to install them aborts the checkpoint instead
    // of committing the API key into a temporary commit.
    ensure_tauqe_ignored(dir)?;

    let status = run_git(Some(dir), &["status", "--porcelain"]).unwrap_or_default();
    let is_dirty = !status.trim().is_empty();

    if !is_dirty {
        // A resolving HEAD names the commit the transaction starts from; a
        // failing one means the branch is unborn, which the marker records
        // as the typed unborn state rather than the moving ref `HEAD`.
        let base = match run_git(Some(dir), &["rev-parse", "HEAD"]) {
            Ok(head) => TransactionBase::Commit(head.trim().to_string()),
            Err(_) => TransactionBase::Unborn,
        };
        let checkpoint = CheckpointInfo {
            created_checkpoint_commit: false,
            base,
        };
        write_transaction_marker(dir, &checkpoint)?;
        return Ok(checkpoint);
    }

    // Stage and commit uncommitted user changes into a checkpoint commit.
    // Ignored paths (.tauqe, credentials, temporary files) in .git/info/exclude
    // are automatically skipped by git add -A without argument pathspec errors.
    run_git(Some(dir), &["add", "-A"])
        .context("Failed to stage uncommitted changes for checkpoint")?;

    commit_with_developer_author(
        dir,
        "tauqe-checkpoint: uncommitted user changes",
        false,
        hooks,
    )?;

    let new_head = run_git(Some(dir), &["rev-parse", "HEAD"])
        .unwrap_or_default()
        .trim()
        .to_string();
    // The checkpoint commit exists now, so the branch is born even where it
    // was unborn before: the recorded base is the checkpoint itself, which
    // the unwind recognizes as a parentless root commit.
    let checkpoint = CheckpointInfo {
        created_checkpoint_commit: true,
        base: TransactionBase::Commit(new_head),
    };
    write_transaction_marker(dir, &checkpoint)?;
    Ok(checkpoint)
}

/// Restores working tree back to pre-checkpoint state (used on workflow failure/cancellation).
pub fn restore_checkpoint(dir: &Path, checkpoint: &CheckpointInfo) -> Result<()> {
    // 1. Return the working tree to the checkpoint base. An unborn base
    //    holds no commit to reset to, so returning the tree to it removes
    //    exactly the paths the transaction tracked and deletes the branch
    //    ref.
    match &checkpoint.base {
        TransactionBase::Commit(head) => {
            run_git(Some(dir), &["reset", "--hard", head])?;
        }
        TransactionBase::Unborn => return_to_unborn(dir)?,
    }
    let _ = run_git(
        Some(dir),
        &[
            "clean",
            "-fd",
            "-e",
            ".tauqe",
            "-e",
            "credentials.toml",
            "-e",
            ".credentials.toml",
        ],
    );

    // 2. Close the transaction before the checkpoint is unwound. The reset above
    //    has already replaced the pre-turn working tree, so a failed unwind must
    //    never leave the marker behind and strand every later recovery: the
    //    marker is cleared first, and the failure propagates as a diagnostic the
    //    rollback-retry loop of the engine can act on.
    clear_transaction_marker(dir);
    if checkpoint.created_checkpoint_commit {
        unwind_checkpoint_if_present(dir).with_context(|| {
            format!(
                "the working tree was reset but the `{CHECKPOINT_PREFIX}` commit could not \
                 be unwound; the pre-turn work stays recoverable inside it at HEAD"
            )
        })?;
    }

    cleanup_orphaned_staging_files(dir);
    Ok(())
}

/// Creates an intermediate step commit during edit execution or verification auto-healing.
///
/// `hooks` is the hook policy the step commit follows.
pub fn create_step_commit(
    dir: &Path,
    changed_files: &[String],
    step_name: &str,
    hooks: GitHooks,
) -> Result<String> {
    if changed_files.is_empty() {
        return Ok(String::new());
    }

    stage_files(dir, changed_files)?;

    let commit_message = format!(
        "tauqe-step: {}\n\n{}",
        step_name.trim(),
        TAUQE_CO_AUTHOR_TRAILER
    );
    commit_with_developer_author(dir, &commit_message, false, hooks)?;

    let short_hash = run_git(Some(dir), &["rev-parse", "--short", "HEAD"])?
        .trim()
        .to_string();

    Ok(short_hash)
}
/// Closes an open transaction whose change set produced no tracked path.
///
/// A bounded turn can verify cleanly while every file it wrote lives outside
/// Git: the `.tauqe/mockups/` sandbox is the documented case, because the
/// harness keeps it out of every commit. Such a turn still opened a checkpoint
/// and recorded a transaction marker, so the transaction is unwound here. The
/// checkpoint commit is rolled back into the working tree, which keeps the
/// developer's uncommitted work, and the empty hash reports that no commit was
/// created.
fn close_transaction_without_changes(
    dir: &Path,
    checkpoint: Option<&CheckpointInfo>,
) -> Result<String> {
    if matches!(checkpoint, Some(checkpoint) if checkpoint.created_checkpoint_commit) {
        let _ = unwind_checkpoint_if_present(dir)?;
    }
    clear_transaction_marker(dir);
    Ok(String::new())
}

/// Squashes all intermediate step commits into a single final AI commit.
///
/// A change set without a single tracked path — one that lives entirely in the
/// mockups sandbox — closes the open transaction and reports the absence of a
/// commit instead of failing the verified turn.
///
/// `hooks` is the hook policy the squashed commit follows.
pub fn finalize_ai_commit(
    dir: &Path,
    checkpoint: &CheckpointInfo,
    changed_files: &[String],
    summary: &str,
    hooks: GitHooks,
) -> Result<String> {
    if changed_files.is_empty() {
        return close_transaction_without_changes(dir, Some(checkpoint));
    }

    // 1. Soft-reset back to the checkpoint base, so every step commit becomes
    //    staged work. An unborn base holds no commit to reset to: deleting
    //    the branch ref leaves the index untouched, so the step commits
    //    collapse into staged work and the final commit becomes the single
    //    squashed root instead of an empty commit on top of the last step.
    match &checkpoint.base {
        TransactionBase::Commit(head) => {
            run_git(Some(dir), &["reset", "--soft", head])
                .context("Failed to soft reset to checkpoint base")?;
        }
        TransactionBase::Unborn => {
            if run_git(Some(dir), &["rev-parse", "--verify", "--quiet", "HEAD"]).is_ok() {
                run_git(Some(dir), &["update-ref", "-d", "HEAD"])
                    .context("Failed to soft reset to the unborn checkpoint base")?;
            }
        }
    }

    // 2. If checkpoint commit was created, unwind it so user uncommitted changes stay in working tree
    if checkpoint.created_checkpoint_commit {
        let _ = unwind_checkpoint_if_present(dir)?;
    }

    // Step commits and temporary checkpoint commits have been unwound back to the
    // working tree. Clear the transaction marker now so an error during staging
    // or committing does not leave a dangling marker that would reset --hard and
    // destroy working tree changes on startup.
    clear_transaction_marker(dir);

    // 3. Stage touched files
    stage_files(dir, changed_files)?;

    let commit_message = format!("{}\n\n{}", summary.trim(), TAUQE_CO_AUTHOR_TRAILER);
    commit_with_developer_author(dir, &commit_message, false, hooks)?;

    let short_hash = run_git(Some(dir), &["rev-parse", "--short", "HEAD"])?
        .trim()
        .to_string();

    Ok(short_hash)
}

/// Creates an isolated AI commit containing only the files modified by the model.
///
/// `hooks` is the hook policy the commit follows.
pub fn create_ai_commit(
    dir: &Path,
    changed_files: &[String],
    summary: &str,
    hooks: GitHooks,
) -> Result<String> {
    if changed_files.is_empty() {
        return close_transaction_without_changes(dir, None);
    }

    // If HEAD is a temporary checkpoint commit, unwind it so user dirty changes remain in working tree
    let _ = unwind_checkpoint_if_present(dir)?;

    clear_transaction_marker(dir);

    stage_files(dir, changed_files)?;

    let commit_message = format!("{}\n\n{}", summary.trim(), TAUQE_CO_AUTHOR_TRAILER);
    commit_with_developer_author(dir, &commit_message, false, hooks)?;

    let short_hash = run_git(Some(dir), &["rev-parse", "--short", "HEAD"])?
        .trim()
        .to_string();

    Ok(short_hash)
}

